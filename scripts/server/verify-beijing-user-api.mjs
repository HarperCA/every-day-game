// Read API checks against a staged migration database; never sends notifications.
import fs from 'node:fs';
import crypto from 'node:crypto';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const Database = require('/opt/daily-contest/server/node_modules/better-sqlite3');
const db = new Database('/opt/daily-contest/server/data/app.db', {readonly:true});
const accountRow = db.prepare("SELECT id,data FROM documents WHERE collection='user_account' LIMIT 1").get();
if (!accountRow) throw new Error('staged_accounts_missing');
const account = JSON.parse(accountRow.data);
const expectedFavorites = db.prepare("SELECT data FROM documents WHERE collection='favorite'").all().map(row=>JSON.parse(row.data)).filter(row=>row.user_id===accountRow.id).length;
db.close();
const post = async (route, body) => {
  const response = await fetch(`http://127.0.0.1:8787/api/${route}`, {method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify(body),signal:AbortSignal.timeout(15000)});
  return {http:response.status,...await response.json()};
};
const secret = fs.readFileSync('/opt/daily-contest/secrets/bridge-secret','utf8').trim();
const claims = {timestamp:Date.now(),nonce:crypto.randomBytes(24).toString('hex'),functionName:'login',identity:{openid:account.openid,appid:'wxb71625ff1404e4e5'},event:{}};
const payload = JSON.stringify(claims);
const envelope = {payload,signature:crypto.createHmac('sha256',secret).update(payload).digest('hex')};
const login = await post('cloudBridge',envelope);
if (!login.ok || login.data.userId!==accountRow.id || !login.data.userSessionToken) throw new Error('staged_login_identity_mismatch');
console.log(JSON.stringify({check:'preserved-account-login',ok:true}));
const favorites = await post('userData',{action:'listFavorites',userSessionToken:login.data.userSessionToken});
if (!favorites.ok || favorites.data.length!==expectedFavorites) throw new Error('staged_favorites_mismatch');
console.log(JSON.stringify({check:'own-favorites',ok:true,count:favorites.data.length}));
const replay = await post('cloudBridge',envelope);
console.log(JSON.stringify({check:'bridge-replay',rejected:replay.ok===false}));
if (replay.ok!==false) throw new Error('replay_accepted');
const publicList = await post('publicData',{action:'list',query:{page:1,pageSize:20}});
if (!publicList.ok || !Array.isArray(publicList.data?.items)) throw new Error('staged_public_query_failed');
console.log(JSON.stringify({check:'public-list',ok:true,total:publicList.data.total,items:publicList.data.items.length}));
const rejected = await post('userData',{action:'listFavorites',__openid:account.openid});
if (rejected.ok!==false) throw new Error('untrusted_identity_accepted');
console.log(JSON.stringify({check:'untrusted-identity',rejected:true}));
const syncSecret = fs.readFileSync('/opt/daily-contest/secrets/sync-secret','utf8').trim();
const sync = await post('publicSync',{action:'status',secret:syncSecret});
if (!sync.ok) throw new Error('staged_public_sync_failed');
console.log(JSON.stringify({check:'public-sync-status',ok:true,total:sync.count ?? sync.total}));
