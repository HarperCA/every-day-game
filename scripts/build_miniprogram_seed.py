from __future__ import annotations

import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "data" / "seed" / "competitions.json"
TARGET = ROOT / "apps" / "miniprogram" / "data" / "competitions.js"
ADMIN_TARGET = ROOT / "apps" / "admin" / "src" / "data" / "competitions.json"


def main():
    source = json.loads(SOURCE.read_text(encoding="utf-8"))
    masters = {item["id"]: item for item in source["event_masters"]}
    schedules = {item["edition_id"]: item for item in source["event_schedules"]}
    tracks = {item["edition_id"]: item for item in source["event_tracks"]}
    recommendations = {item["edition_id"]: item for item in source["recommendations"]}
    profession_names = {item["id"]: item["name"] for item in source["profession_categories"]}
    professions: dict[str, list[str]] = {}
    for link in source["event_professions"]:
        professions.setdefault(link["edition_id"], []).append(profession_names[link["profession_id"]])
    sources: dict[str, list[dict]] = {}
    for item in source["data_sources"]:
        sources.setdefault(item["edition_id"], []).append(item)

    records = []
    for edition in source["event_editions"]:
        master = masters[edition["event_id"]]
        records.append({
            "id": edition["id"],
            "eventId": edition["event_id"],
            "name": master["standard_name"],
            "editionName": edition["edition_name"],
            "aliases": master["aliases"],
            "organizer": edition["organizer"],
            "eventLevel": edition["event_level"],
            "objectiveTags": list(dict.fromkeys(master["objective_tags"] + edition["objective_tags"])),
            "professions": professions.get(edition["id"], []),
            "participants": edition["participants"],
            "eligibility": edition["eligibility"],
            "formatAndRules": edition["format_and_rules"],
            "teamSize": edition["team_size"],
            "participationFormat": edition["participation_format"],
            "teamSizeCategory": edition["team_size_category"],
            "registrationMethod": edition["registration_method"],
            "registrationOrganization": edition["registration_organization"],
            "registrationUrl": edition["registration_url"],
            "fees": edition["fees"],
            "feeType": edition["fee_type"],
            "lastVerifiedAt": edition["last_verified_at"],
            "dataStatus": edition["data_status"],
            "systemValidation": edition["system_validation"],
            "manualReview": edition["manual_review"],
            "qualityIssues": edition["quality_issues"],
            "schedule": schedules[edition["id"]],
            "track": tracks[edition["id"]],
            "recommendation": recommendations[edition["id"]],
            "sources": sources.get(edition["id"], []),
        })
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    payload = "// Generated by scripts/build_miniprogram_seed.py\nmodule.exports = " + json.dumps(records, ensure_ascii=False, indent=2) + ";\n"
    TARGET.write_text(payload, encoding="utf-8")
    ADMIN_TARGET.parent.mkdir(parents=True, exist_ok=True)
    ADMIN_TARGET.write_text(json.dumps(records, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"built client seeds: {len(records)} records -> {TARGET}, {ADMIN_TARGET}")


if __name__ == "__main__":
    main()
