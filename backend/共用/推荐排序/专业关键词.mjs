// 十三类大类名本身也能直接搜
const 大类名 = ['综合/不限专业', ...Object.keys(专业词表)];
const 词们 = Object.entries(专业词表).flatMap(([大类, 列表]) => 列表.map(词 => ({ 词: 词.toLowerCase(), 大类 })));
const 规整 = 值 => String(值 || '').trim().toLowerCase().replace(/\s+/g, '');
const { majors } = JSON.parse(fs.readFileSync(new URL('./专业目录-2026.json', import.meta.url), 'utf8'));
const 目录 = majors.map(专业 => ({ ...专业, 规整名: 规整(专业.name) }));
const 完整名和代码 = new Map();
for (const 专业 of 目录) {
  完整名和代码.set(专业.规整名, 专业.categories);
  完整名和代码.set(规整(专业.code), 专业.categories);
}

// 学生常带的后缀：“计算机专业”“土木类”“临床医学系”，先去掉
function 去后缀(词) {
  let 结果 = 词;
  for (;;) {
    const 下一个 = 结果.replace(/(类专业|专业类|专业|学院|方向|类|系)$/, '');
    if (下一个 === 结果) return 结果;
    结果 = 下一个;
  }
}

// 返回对应的专业大类（可能多个；空数组表示这个词不像专业名）。单个字不匹配，免得“法”“化”乱对。
export function 专业大类(原词) {
  const 底 = 规整(原词);
  const 词 = 去后缀(底);
  // 具体专业完整名称和代码优先，免得经济统计学、软件工程被泛词串到别的类
  const 准确 = 完整名和代码.get(底) || 完整名和代码.get(词);
  if (准确) return [...准确];
  // 像比赛名称的交给名称搜索，不因名称里有个专业词就扩大结果
  if (/(竞赛|比赛|赛事|大赛|挑战杯)/.test(底)) return [];
  const 找到 = new Set();
  for (const 名 of 大类名) if (名.toLowerCase() === 底 || 名.toLowerCase() === 词) 找到.add(名);
  if (['不限', '不限专业', '综合', '各专业', '所有专业'].includes(词)) 找到.add('综合/不限专业');
  if (词.length >= 2) {
    for (const { 词: 表词, 大类 } of 词们) {
      // 两个字的只按词的开头对（“设计”不对“程序设计”）；三个字以上才允许在中间
      const 在里面 = 词.length >= 3 ? 表词.includes(词) : 表词.startsWith(词);
      // 搜索词比表里的词长（“我想找计算机”）时，只认三个字以上的表词
      if (在里面 || (表词.length >= 3 && 词.includes(表词))) 找到.add(大类);
    }
  }
  // 三个字以上的纯中文，再按专业目录里名称的开头补
  if (词.length >= 3 && /^[一-鿿]+$/.test(词)) {
    for (const 专业 of 目录) if (专业.规整名.startsWith(词)) for (const 大类 of 专业.categories) 找到.add(大类);
  }
  return [...找到];
}
