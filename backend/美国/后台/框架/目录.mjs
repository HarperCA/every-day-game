// 目录：左侧的分类和子页面（2026-11-01 用户定）。分类（比赛管理、日志……）只是标题，不能点；子页面才能点，点了单独显示那一页。
// 每页的地址就是它的标题（#比赛列表），刷新和后退都停在那一页。纯计算，不碰页面，测试能直接用。
//
//   定义分类({ id, 标题, 页们: [功能 | { 功能, 标题, 说明, 顶部: [功能, …] }] })
//     页的标题、说明默认取功能自己的；顶部：放在这一页最上面一直显示的功能（比赛列表页上的比赛数据总览）
//   全部页(目录清单) → 按顺序的所有页；找页(目录清单, location.hash) → 那一页，没写或不认识的去第一页

export function 定义分类(分类) {
  if (!分类?.id || !分类.标题) throw new Error('分类要有 id 和 标题');
  if (!分类.页们?.length) throw new Error(`分类 ${分类.id} 至少要有一页`);
  const 页们 = 分类.页们.map(项 => {
    const { 功能, 标题, 说明, 顶部 = [] } = 项?.功能 ? 项 : { 功能: 项 };
    if (!功能?.id) throw new Error(`分类 ${分类.id} 里有一页没有功能`);
    const 页标题 = 标题 || 功能.标题;
    return { 地址: 页标题, 标题: 页标题, 说明: 说明 ?? 功能.说明 ?? '', 功能, 顶部 };
  });
  const 结果 = Object.freeze({ id: 分类.id, 标题: 分类.标题, 页们 });
  // 每页记着自己属于哪个分类（页面顶部显示“比赛管理 · 比赛列表”）
  for (const 页 of 页们) Object.freeze(Object.assign(页, { 分类: 结果 }));
  return 结果;
}

export const 全部页 = 目录清单 => 目录清单.flatMap(分类 => 分类.页们);

export function 找页(目录清单, hash = '') {
  let 地址 = String(hash).replace(/^#/, '');
  try { 地址 = decodeURIComponent(地址); } catch { 地址 = ''; }
  const 页们 = 全部页(目录清单);
  return 页们.find(页 => 页.地址 === 地址) || 页们[0];
}
