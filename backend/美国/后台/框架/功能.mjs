// 功能的统一写法和运行方式。每个功能一个文件夹（功能/…/），里面三个函数各管一件事：
//
//   数据库.mjs  取(参数, 环境)            在美国服务器上跑：从比赛库等地方取原始数据（浏览器经 请求.mjs 调它）
//   整理.mjs    整理(原始数据, 条件)       纯计算：整理、筛选、排序、分组，不碰界面也不碰数据库
//   呈现.mjs    呈现(容器, 数据, 控制)     在浏览器里跑：把整理好的数据画成界面
//   index.mjs   export default 定义功能({ id, 标题, 说明, 初始条件, 整理, 呈现 })
//
// 框架按顺序调用：取数据 → 整理 → 呈现。筛选条件变了只重新整理和呈现，不重新取数据；要重新取用 控制.重新读取()。
// 保存、删除这类动作用 控制.提交(参数)：成功后换上新数据重画（筛选条件不变）；失败时把错误抛给调用的地方，界面不清空（编辑框里填的还在）。
// 不该重画的小请求（编辑框里先把图片存进图片总库）用 控制.发请求(参数)：只交回 取() 的结果。
import { 建 } from './dom.mjs';
import { 请求 } from './请求.mjs';

export function 定义功能(功能) {
  for (const 项 of ['id', '标题']) if (!功能?.[项]) throw new Error(`功能要有 ${项}`);
  for (const 项 of ['整理', '呈现']) if (typeof 功能[项] !== 'function') throw new Error(`功能 ${功能.id} 要有 ${项} 函数`);
  return Object.freeze({ 初始条件: {}, 说明: '', ...功能 });
}

// 还没写的地方：写清楚由哪个函数提供、数据从哪来、要做什么
export function 画占位(容器, { 功能, 来源, 要做 = [] }) {
  容器.append(建('div', { class: '占位' },
    建('strong', {}, '这一块还没写'),
    建('div', {}, '界面由 ', 建('code', {}, `功能/${功能}/呈现.mjs`), ' 画；数据由 ', 建('code', {}, `功能/${功能}/数据库.mjs`), ' 取', 来源 ? `（${来源}）` : '', '。'),
    要做.length ? 建('ul', {}, 要做.map(项 => 建('li', {}, 项))) : null));
}

// 把一个功能运行在容器里
export async function 运行功能(功能, 容器) {
  let 原始 = null;
  let 条件 = { ...功能.初始条件 };
  const 画 = () => {
    容器.replaceChildren();
    try {
      const 数据 = 功能.整理(原始, 条件);
      功能.呈现(容器, 数据, {
        条件,
        改条件(新条件) { 条件 = { ...条件, ...新条件 }; 画(); },
        重新读取: 读取,
        async 提交(参数) { 原始 = await 请求(功能.id, 参数); 画(); },
        发请求: 参数 => 请求(功能.id, 参数),
        建,
        占位: 说明 => 画占位(容器, { 功能: 功能.目录 || 功能.id, ...说明 }),
      });
    } catch (错误) {
      容器.replaceChildren(建('div', { class: '状态 出错' }, `这一块出错了：${错误?.message || 错误}`));
      console.error(错误);
    }
  };
  async function 读取(参数 = {}) {
    容器.replaceChildren(建('div', { class: '状态' }, '加载中…'));
    try {
      原始 = await 请求(功能.id, 参数);
    } catch (错误) {
      容器.replaceChildren(建('div', { class: '状态 出错' }, `读取失败：${错误?.message || 错误}`));
      return;
    }
    画();
  }
  await 读取();
}
