// 接口用量 · 呈现（浏览器里跑）：换天数经 重新读取 交给 数据库.mjs；合计在上，下面按天、按接口、按来源三张表，月费单列。
const 元 = x => (x == null ? '—' : `${x.toFixed(x < 1 ? 4 : 2)} 元`);
const 万 = n => (n >= 10000 ? `${(n / 10000).toFixed(1)} 万` : String(n));
const 费用 = x => `${元(x.费用)}${x.有没算价的 ? '（有的还没定价）' : ''}`;

export function 呈现(容器, 数据, { 重新读取, 建 }) {
  if (数据.没接上) { 容器.append(建('div', { class: '状态' }, 'AI 总管的用量库还没接上（服务器没给读取函数）。')); return; }
  容器.append(建('div', { class: '工具栏' },
    建('select', { 'aria-label': '看最近几天', onchange: 事件 => 重新读取({ 天数: Number(事件.target.value) }) },
      [[1, '今天'], [7, '最近 7 天'], [30, '最近 30 天'], [90, '最近 90 天']].map(([值, 名]) => 建('option', { value: 值, selected: 值 === 数据.天数 }, 名))),
    建('span', { class: '次要' }, `${数据.从} 到 ${数据.到}（北京时间）`)));

  const 合 = 数据.合计;
  容器.append(建('p', {}, `一共调用 ${合.次数} 次，失败 ${合.失败} 次；输入 ${万(合.输入token)} token，输出 ${万(合.输出token)} token；按次计费 ${费用(合)}`));
  if (合.有没算价的) 容器.append(建('p', { class: '标签说明' }, '价格在 美国/ai/common/config.mjs 的 PRICES 里，还没填的接口费用记为空，不算进合计。'));
  if (!合.次数) { 容器.append(建('div', { class: '状态' }, '这段时间没有调用。')); }

  const 表 = (标题, 首列, 行们) => {
    if (!行们.length) return;
    容器.append(建('h3', {}, 标题), 建('div', { class: '表格外框' }, 建('table', { class: '表格' },
      建('thead', {}, 建('tr', {}, [首列, '次数', '失败', '输入 token', '输出 token', '费用'].map(名 => 建('th', {}, 名)))),
      建('tbody', {}, 行们.map(x => 建('tr', {}, 建('td', {}, x.名称), 建('td', {}, String(x.次数)), 建('td', {}, String(x.失败)),
        建('td', {}, 万(x.输入token)), 建('td', {}, 万(x.输出token)), 建('td', {}, 费用(x))))))));
  };
  表('按天', '日期', 数据.按天);
  表('按接口', '接口', 数据.按接口);
  表('按来源', '来源', 数据.按来源);

  容器.append(建('h3', {}, `${数据.月份} 月费`));
  容器.append(数据.月费.length
    ? 建('ul', {}, 数据.月费.map(f => 建('li', {}, `${f.接口}：${f.金额} 元${f.说明 ? `（${f.说明}）` : ''}`)))
    : 建('p', { class: '标签说明' }, '这个月还没登记月费（Codex、Kimi 会员通道按月付费，单次调用记 0）。'));
}
