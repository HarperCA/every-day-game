// 抓取结果账 · 取数据（美国服务器上跑）：选一晚，读它的 run.db（2026-11-02 接上）。
// 读取函数由后台的服务器在环境里给：环境.每晚记录 = { 列出()（有哪几晚，新的在前）, 读一晚(名) }，即 pipeline/小数据库 的 列出几晚、读一晚。
// 环境没给就写明没接上。
//
//   取({ 晚 }, { 每晚记录 })   晚：运行文件夹的名字（2026-11-01、2026-11-01-02）；没给或不在列表里就读最新的一晚
export async function 取({ 晚 } = {}, { 每晚记录 } = {}) {
  if (!每晚记录) return { 晚们: [], 选中: null, 一晚: null, 没接上: true };
  const 晚们 = 每晚记录.列出();
  const 选中 = 晚们.includes(晚) ? 晚 : 晚们[0] || null;
  return { 晚们, 选中, 一晚: 选中 ? 每晚记录.读一晚(选中) : null, 没接上: false };
}
