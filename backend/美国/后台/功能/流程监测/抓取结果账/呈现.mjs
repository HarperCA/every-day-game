// 抓取结果账 · 呈现（浏览器里跑）：选哪一晚经 重新读取 交给 数据库.mjs；点模块名只重新整理，看它那里的条目。
export function 呈现(容器, 数据, { 重新读取, 改条件, 建 }) {
  if (数据.没接上) { 容器.append(建('div', { class: '状态' }, '每晚的运行记录还没接上（服务器没给读取函数）。')); return; }
  if (!数据.晚们.length) { 容器.append(建('div', { class: '状态' }, '还没有哪一晚跑过。每晚流程 1:00 开始，跑完这里就有记录。')); return; }

  容器.append(建('div', { class: '工具栏' },
    建('select', { 'aria-label': '选哪一晚', onchange: 事件 => 重新读取({ 晚: 事件.target.value }) },
      数据.晚们.map(名 => 建('option', { value: 名, selected: 名 === 数据.选中 }, 名))),
    数据.概况 ? 建('span', { class: '次要' }, `${数据.概况.方式} · ${数据.概况.结果} · ${数据.概况.开始} 到 ${数据.概况.结束 || '—'}`) : null));
  if (!数据.一晚) return;

  const 表 = (列, 行们) => 建('div', { class: '表格外框' }, 建('table', { class: '表格' },
    建('thead', {}, 建('tr', {}, 列.map(名 => 建('th', {}, 名)))), 建('tbody', {}, 行们)));
  const 概 = 数据.概况;
  容器.append(建('p', { class: '标签说明' }, `搜索词 ${概.搜索词} 个，候选 ${概.候选 ?? '—'} 条；条目最后：${数据.最后状态.map(([k, v]) => `${k} ${v}`).join('、') || '没有条目'}`));

  容器.append(建('h3', {}, '各模块'), 表(['模块', '状态', '开始', '用时', '处理', '其中', '问题或错误'],
    数据.模块行们.map(m => 建('tr', {},
      建('td', {}, 建('button', { type: 'button', class: `切换${m.码 === 数据.选中模块 ? ' 选中' : ''}`, onclick: () => 改条件({ 模块: m.码 === 数据.选中模块 ? '' : m.码 }) }, m.模块)),
      建('td', {}, m.状态), 建('td', {}, m.开始), 建('td', {}, m.用时), 建('td', {}, String(m.处理)), 建('td', {}, m.各状态),
      建('td', { class: '可换行' }, m.错误 || m.问题)))));

  if (数据.去向们.length) {
    容器.append(建('h3', {}, '去向'), 表(['停在哪', '状态', '原因', '条数'],
      数据.去向们.map(d => 建('tr', {}, 建('td', {}, d.模块), 建('td', {}, d.状态), 建('td', { class: '可换行' }, d.原因), 建('td', {}, String(d.次数))))));
  }

  const 改 = 数据.改动;
  容器.append(建('h3', {}, '写进比赛库'), 建('p', {}, `已写入 ${改.已写入} 条，不提交 ${改.不提交} 条，还没提交 ${改.待提交} 条`));
  if (改.不提交原因.length) {
    容器.append(表(['表', '编号', '为什么没写进去'], 改.不提交原因.map(x => 建('tr', {}, 建('td', {}, x.表), 建('td', {}, x.编号), 建('td', { class: '可换行' }, x.原因)))));
  }

  容器.append(建('h3', {}, 数据.选中模块 ? `停在 ${数据.模块行们.find(m => m.码 === 数据.选中模块)?.模块 || 数据.选中模块} 的条目（${数据.条目们.length}）` : `全部条目（${数据.条目们.length}）`));
  if (!数据.条目们.length) { 容器.append(建('div', { class: '状态' }, '没有条目。')); return; }
  容器.append(表(['候选', '状态', '停在哪', '原因'], 数据.条目们.map(e => 建('tr', {},
    建('td', { class: '可换行' }, 建('a', { href: e.网址, target: '_blank', rel: 'noopener noreferrer' }, e.名称)),
    建('td', {}, e.状态), 建('td', {}, e.模块), 建('td', { class: '可换行' }, e.原因)))));
}
