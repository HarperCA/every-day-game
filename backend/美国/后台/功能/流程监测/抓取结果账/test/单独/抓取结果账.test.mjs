// 后台 · 抓取结果账：选一晚，看各模块怎么样、每条候选的去向和原因、写进比赛库没有（2026-11-02）。
// 每晚的运行记录由环境给读取函数（pipeline/小数据库 的 列出几晚、读一晚），这里用假的。
import { describe, expect, test } from 'vitest';
import { 处理后台请求 } from '../../../../../接口.mjs';
import { 整理 } from '../../整理.mjs';

const 一晚 = {
  名: '2026-11-01', 开始: '2026-10-31T17:00:00.000Z', 结束: '2026-10-31T17:55:00.000Z', 方式: '正式运行', 结果: '全部模块跑完',
  搜索词们: ['数学建模 竞赛', '机器人 竞赛'], 候选: 3,
  模块们: [
    { 模块: '01-search', 状态: '完成', 开始: '2026-10-31T17:00:00.000Z', 结束: '2026-10-31T17:05:00.000Z', 处理: 3, 各状态: { 进行中: 3 }, 改动: 0, 问题: ['甲', '乙', '丙', '丁'], 错误: '' },
    { 模块: '04-extract', 状态: '跳过', 开始: '2026-10-31T17:20:00.000Z', 结束: '2026-10-31T17:40:30.000Z', 处理: null, 各状态: {}, 改动: null, 问题: [], 错误: '读网页超时太多' },
  ],
  条目们: [
    { 网址: 'https://a.cn/1', 名称: '甲杯', 状态: '进行中', 模块: '06-ingest', 原因: '06 入库：新比赛' },
    { 网址: 'https://a.cn/2', 名称: '乙', 状态: '已丢弃', 模块: '03-filter', 原因: '03 筛选·标题筛选：不是比赛' },
    { 网址: 'https://a.cn/3', 名称: '', 状态: '已丢弃', 模块: '03-filter', 原因: '03 筛选·标题筛选：不是比赛' },
  ],
  去向们: [{ 模块: '03-filter', 状态: '已丢弃', 原因: '03 筛选·标题筛选：不是比赛', 次数: 2 }, { 模块: '06-ingest', 状态: '进行中', 原因: '06 入库：新比赛', 次数: 1 }],
  改动: { 已写入: 2, 不提交: 1, 待提交: 0, 不提交原因: [{ 表: 'source', 编号: 'source-1', 原因: '字段不合格' }] },
};

function 环境() {
  const 读了 = [];
  return { 读了, env: { 每晚记录: { 列出: () => ['2026-11-01', '2026-10-31'], 读一晚: 名 => { 读了.push(名); return { ...一晚, 名 }; } } } };
}

describe('取数据', () => {
  test('默认读最新的一晚；指定了就读指定的；不在列表里的不读', async () => {
    const { env, 读了 } = 环境();
    expect(await 处理后台请求('抓取结果账', {}, env)).toMatchObject({ 晚们: ['2026-11-01', '2026-10-31'], 选中: '2026-11-01', 一晚: { 名: '2026-11-01' }, 没接上: false });
    expect((await 处理后台请求('抓取结果账', { 晚: '2026-10-31' }, env)).选中).toBe('2026-10-31');
    expect((await 处理后台请求('抓取结果账', { 晚: '../外面' }, env)).选中).toBe('2026-11-01');
    expect(读了).toEqual(['2026-11-01', '2026-10-31', '2026-11-01']);
  });
  test('还没有哪一晚跑过：一晚是空的；环境没给读取函数：写明没接上', async () => {
    expect(await 处理后台请求('抓取结果账', {}, { 每晚记录: { 列出: () => [], 读一晚: () => { throw new Error('不该读'); } } })).toMatchObject({ 晚们: [], 选中: null, 一晚: null });
    expect(await 处理后台请求('抓取结果账', {}, {})).toMatchObject({ 没接上: true, 晚们: [] });
  });
});

describe('整理', () => {
  const 原始 = { 晚们: ['2026-11-01'], 选中: '2026-11-01', 一晚, 没接上: false };
  test('概况：北京时间、方式、结果、搜索词几个、候选几条；条目最后的状态各多少', () => {
    const r = 整理(原始, {});
    expect(r.概况).toEqual({ 开始: '2026-11-01 01:00', 结束: '2026-11-01 01:55', 方式: '正式运行', 结果: '全部模块跑完', 搜索词: 2, 候选: 3 });
    expect(r.最后状态).toEqual([['进行中', 1], ['已丢弃', 2]]);
  });
  test('各模块：中文名、几点开始、用了几分钟、各状态多少、问题先列 3 个', () => {
    const [搜, 抽] = 整理(原始, {}).模块行们;
    expect(搜).toEqual({ 码: '01-search', 模块: '01 搜索', 状态: '完成', 开始: '01:00', 用时: '5 分钟', 处理: 3, 各状态: '进行中 3', 问题: '甲；乙；丙 等 4 个', 错误: '' });
    expect(抽).toMatchObject({ 模块: '04 读详情和抽取', 状态: '跳过', 用时: '21 分钟', 处理: '—', 各状态: '', 错误: '读网页超时太多' });
  });
  test('去向写模块中文名；点一个模块只看它那里的条目；名称空的用网址', () => {
    const r = 整理(原始, { 模块: '03-filter' });
    expect(r.去向们[0]).toEqual({ 模块: '03 筛选', 状态: '已丢弃', 原因: '03 筛选·标题筛选：不是比赛', 次数: 2 });
    expect(r.选中模块).toBe('03-filter');
    expect(r.条目们.map(e => e.名称)).toEqual(['乙', 'https://a.cn/3']);
    expect(整理(原始, {}).条目们).toHaveLength(3);
  });
  test('改动原样交给界面；没有一晚时各项为空', () => {
    expect(整理(原始, {}).改动).toEqual(一晚.改动);
    expect(整理({ 晚们: [], 选中: null, 一晚: null, 没接上: false }, {})).toMatchObject({ 一晚: false, 模块行们: [], 条目们: [] });
  });
});
