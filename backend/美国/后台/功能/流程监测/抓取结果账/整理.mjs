// 抓取结果账 · 整理（纯计算）：时间写北京时间，模块写中文名，算每个模块用了几分钟；点一个模块只看它那里的条目。
const 北京 = 时间 => 时间 ? new Date(new Date(时间).getTime() + 8 * 3600 * 1000).toISOString().slice(0, 16).replace('T', ' ') : '';
const 模块名 = { '01-search': '01 搜索', '02-dedup': '02 对比去重', '03-filter': '03 筛选', '04-extract': '04 读详情和抽取', '05-review': '05 审核', '06-ingest': '06 入库' };
const 中文 = 码 => 模块名[码] || 码 || '';
const 用时 = (开始, 结束) => (开始 && 结束 ? `${Math.round((Date.parse(结束) - Date.parse(开始)) / 60000)} 分钟` : '');
const 先列三个 = 列表 => (列表.length > 3 ? `${列表.slice(0, 3).join('；')} 等 ${列表.length} 个` : 列表.join('；'));

export function 整理(原始, { 模块 = '' } = {}) {
  const 一晚 = 原始.一晚;
  const 空 = { 晚们: 原始.晚们 || [], 选中: 原始.选中, 没接上: Boolean(原始.没接上) };
  if (!一晚) return { ...空, 一晚: false, 概况: null, 最后状态: [], 模块行们: [], 去向们: [], 选中模块: '', 条目们: [], 改动: null };
  const 最后状态 = new Map();
  for (const e of 一晚.条目们) 最后状态.set(e.状态, (最后状态.get(e.状态) || 0) + 1);
  return {
    ...空,
    一晚: true,
    概况: { 开始: 北京(一晚.开始), 结束: 北京(一晚.结束), 方式: 一晚.方式, 结果: 一晚.结果, 搜索词: 一晚.搜索词们.length, 候选: 一晚.候选 },
    最后状态: [...最后状态],
    模块行们: 一晚.模块们.map(m => ({
      码: m.模块, 模块: 中文(m.模块), 状态: m.状态, 开始: 北京(m.开始).slice(11), 用时: 用时(m.开始, m.结束), 处理: m.处理 ?? '—',
      各状态: Object.entries(m.各状态).map(([k, v]) => `${k} ${v}`).join('、'), 问题: 先列三个(m.问题), 错误: m.错误,
    })),
    去向们: 一晚.去向们.map(d => ({ ...d, 模块: 中文(d.模块) })),
    选中模块: 模块,
    条目们: 一晚.条目们.filter(e => !模块 || e.模块 === 模块).map(e => ({ 名称: e.名称 || e.网址, 网址: e.网址, 状态: e.状态, 模块: 中文(e.模块), 原因: e.原因 })),
    改动: 一晚.改动,
  };
}
