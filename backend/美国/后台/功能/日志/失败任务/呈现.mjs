// 失败任务 · 呈现（浏览器里跑）：只看。换天数经 重新读取 交给 数据库.mjs；按来源筛只重新整理。
// 每行一组同样的失败：最近一次、来源、哪一步、原因、几次、涉及哪些；点“全部”展开所有涉及的对象（有网址的可以点开）。
export function 呈现(容器, 数据, { 重新读取, 改条件, 建 }) {
  容器.append(建('div', { class: '工具栏' },
    建('select', { 'aria-label': '看最近几天', onchange: 事件 => 重新读取({ 天数: Number(事件.target.value) }) },
      [[1, '今天'], [7, '最近 7 天'], [30, '最近 30 天'], [90, '最近 90 天']].map(([值, 名]) => 建('option', { value: 值, selected: 值 === 数据.天数 }, 名))),
    数据.来源们.map(([名, 数]) => 建('button', { type: 'button', class: `切换${名 === 数据.来源 ? ' 选中' : ''}`, onclick: () => 改条件({ 来源: 名 }) }, `${名} ${数}`))));
  if (数据.没接上.length) 容器.append(建('p', { class: '标签说明' }, `还没接上：${数据.没接上.join('、')}（这里只列出了其余来源的）`));

  if (!数据.行们.length) {
    容器.append(建('div', { class: '状态' }, '这段时间没有失败的任务。'));
    return;
  }
  容器.append(建('p', { class: '标签说明' }, `${数据.行们.length} 种失败，一共 ${数据.总次数} 次。同一来源、同一步、同一原因的合成一行。`));
  容器.append(建('div', { class: '表格外框' }, 建('table', { class: '表格' },
    建('thead', {}, 建('tr', {}, ['最近一次', '来源', '哪一步', '原因', '次数', '涉及'].map(名 => 建('th', {}, 名)))),
    建('tbody', {}, 数据.行们.map(g => 建('tr', {},
      建('td', {}, g.最近),
      建('td', {}, g.来源),
      建('td', {}, g.环节),
      建('td', { class: '可换行' }, g.原因),
      建('td', {}, `${g.次数} 次`),
      建('td', { class: '可换行' }, g.对象们.length > 3
        ? 建('details', {}, 建('summary', {}, g.涉及), 建('ul', {}, g.对象们.map(o => 建('li', {}, 对象(o, 建)))))
        : g.对象们.map(o => 建('div', {}, 对象(o, 建))))))))));
}

const 对象 = (o, 建) => o.网址 ? 建('a', { href: o.网址, target: '_blank', rel: 'noopener noreferrer' }, o.名称) : o.名称;
