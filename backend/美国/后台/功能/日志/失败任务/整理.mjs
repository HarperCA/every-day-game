// 失败任务 · 整理（纯计算）：按来源筛，最近的排前面，时间写北京时间，流程模块写中文名，涉及的对象先列 3 个。
const 北京时间 = 时间 => 时间 ? new Date(new Date(时间).getTime() + 8 * 3600 * 1000).toISOString().slice(0, 16).replace('T', ' ') : '';
const 来源顺序 = ['每晚流程', 'AI 返回的内容不能用', '维护'];
const 模块名 = { '01-search': '01 搜索', '02-dedup': '02 对比去重', '03-filter': '03 筛选', '04-extract': '04 读详情和抽取', '05-review': '05 审核', '06-ingest': '06 入库' };
const 中文环节 = 环节 => String(环节 || '').replace(/^\d{2}-[a-z]+/, 码 => 模块名[码] || 码);
const 涉及 = 对象们 => 对象们.length > 3 ? `${对象们.slice(0, 3).map(o => o.名称).join('、')} 等 ${对象们.length} 个` : 对象们.map(o => o.名称).join('、');

export function 整理(原始, { 来源 = '全部' } = {}) {
  const 选中 = 原始.组们.filter(g => 来源 === '全部' || g.来源 === 来源)
    .sort((a, b) => (Date.parse(b.最近) || 0) - (Date.parse(a.最近) || 0));
  return {
    天数: 原始.天数,
    没接上: 原始.没接上 || [],
    来源,
    来源们: [['全部', 原始.组们.length], ...来源顺序.map(名 => [名, 原始.组们.filter(g => g.来源 === 名).length])],
    总次数: 选中.reduce((和, g) => 和 + g.次数, 0),
    行们: 选中.map(g => ({ 来源: g.来源, 环节: 中文环节(g.环节), 原因: g.原因, 次数: g.次数, 最近: 北京时间(g.最近), 涉及: 涉及(g.对象们), 对象们: g.对象们 })),
  };
}
