// 后台 · 失败任务：只看（2026-11-01 用户定：不重试、不标记已处理）。三个来源合在一页：
//   每晚流程（run.db 里失败的模块和条目）、AI 返回的内容不能用（AI 总管用量库的 problems）、维护（比赛库里“维护比赛”记录的检查失败）。
// 同一个来源、同一环节、同一原因的合成一条，记次数、最近一次和涉及哪些对象。每晚流程和 AI 问题由环境给读取函数，这里用假的。
import { describe, expect, test } from 'vitest';
import { open, seed } from '../../../../../../db/test/复用/样例数据.mjs';
import { 处理后台请求 } from '../../../../../接口.mjs';
import { 整理 } from '../../整理.mjs';

const NOW = new Date('2026-11-01T10:00:00Z');   // 北京时间 11-01 18:00
const 维护 = (db, id, at, 比赛, 失败) => db.transaction(tx => tx.insert('audit_log', id, { created_at: at, action: '维护比赛', table_name: 'competition', record_id: 比赛,
  detail: { 检查完成: ['状态'], 检查失败: 失败, 改正: 0, 转人工: 0, 留着: 0 } }));

function 环境({ 每晚 = [], 问题 = [] } = {}) {
  const db = open(); seed(db);
  维护(db, 'w1', '2026-11-01T02:00:00.000Z', 'event-math', [{ name: '链接', error: '还没实现：维护/审计/链接' }]);
  维护(db, 'w2', '2026-11-01T02:05:00.000Z', 'event-art', [{ name: '链接', error: '还没实现：维护/审计/链接' }, { name: '新一届', error: '搜索额度用完' }]);
  维护(db, 'w3', '2026-11-01T02:10:00.000Z', 'event-math', []);
  维护(db, 'w0', '2026-10-20T02:00:00.000Z', 'event-math', [{ name: '链接', error: '太早了' }]);
  const 收到 = {};
  return {
    收到,
    env: {
      db, now: () => NOW,
      每晚失败: 选项 => { 收到.每晚 = 选项; return 每晚; },
      AI问题: 从哪天 => { 收到.AI = 从哪天; return 问题; },
    },
  };
}
const 读 = (env, 参数 = {}) => 处理后台请求('失败任务', 参数, env);

describe('取数据', () => {
  test('三个来源合在一起；同来源、同环节、同原因的合成一条，记次数、最近一次、涉及的对象', async () => {
    const { env, 收到 } = 环境({
      每晚: [
        { 哪一晚: '2026-11-01', 时间: '2026-10-31T17:40:00Z', 环节: '04-extract', 对象: '整个模块', 网址: '', 原因: '读网页超时太多', 整晚停下: false },
        { 哪一晚: '2026-11-01', 时间: '2026-10-31T17:30:00Z', 环节: '04-extract', 对象: '某某杯通知', 网址: 'https://a.cn/1', 原因: '读不到正文：404', 整晚停下: false },
        { 哪一晚: '2026-10-30', 时间: '2026-10-29T17:31:00Z', 环节: '04-extract', 对象: '另一个通知', 网址: 'https://b.cn/2', 原因: '读不到正文：404', 整晚停下: false },
        { 哪一晚: '2026-10-30-02', 时间: '2026-10-29T17:10:00Z', 环节: '03-filter', 对象: '整个模块', 网址: '', 原因: 'DeepSeek 密钥错误', 整晚停下: true },
      ],
      问题: [{ at: '2026-10-31T17:20:00.000Z', source: '每晚自动化', run_id: '2026-11-01', module: '02-dedup', purpose: 'arbitrate', reason: '漏了 2 条候选的结论' }],
    });
    const r = await 读(env, { 天数: 7 });
    expect(收到).toEqual({ 每晚: { 天数: 7, now: NOW }, AI: '2026-10-26' });
    expect(r).toMatchObject({ 天数: 7, 没接上: [] });
    const 按 = Object.fromEntries(r.组们.map(g => [`${g.来源}|${g.环节}|${g.原因}`, g]));
    expect(按['每晚流程|04-extract|读不到正文：404']).toEqual({ 来源: '每晚流程', 环节: '04-extract', 原因: '读不到正文：404', 次数: 2, 最近: '2026-10-31T17:30:00Z',
      对象们: [{ 名称: '某某杯通知', 网址: 'https://a.cn/1' }, { 名称: '另一个通知', 网址: 'https://b.cn/2' }] });
    expect(按['每晚流程|03-filter|DeepSeek 密钥错误'].对象们).toEqual([{ 名称: '2026-10-30-02 那一晚（整个模块失败，整晚停下）', 网址: '' }]);
    expect(按['每晚流程|04-extract|读网页超时太多'].对象们).toEqual([{ 名称: '2026-11-01 那一晚（整个模块失败，跳过继续）', 网址: '' }]);
    expect(按['AI 返回的内容不能用|02-dedup · arbitrate|漏了 2 条候选的结论']).toMatchObject({ 次数: 1, 对象们: [{ 名称: '2026-11-01 那一晚', 网址: '' }] });
    expect(按['维护|链接|还没实现：维护/审计/链接']).toMatchObject({ 次数: 2, 最近: '2026-11-01T02:05:00.000Z',
      对象们: [{ 名称: '省大学生艺术展演', 网址: '' }, { 名称: '全国大学生数学建模竞赛', 网址: '' }] });
    expect(按['维护|新一届|搜索额度用完'].次数).toBe(1);
    expect(r.组们.some(g => g.原因 === '太早了')).toBe(false);
  });
  test('天数只能是 1、7、30、90，默认 7', async () => {
    const { env } = 环境();
    expect((await 读(env)).天数).toBe(7);
    expect((await 读(env, { 天数: 90 })).天数).toBe(90);
    await expect(读(env, { 天数: 5 })).rejects.toThrow(/天数/);
  });
  test('环境没给每晚流程和 AI 问题的读取函数时，照样列维护的，并写明哪些没接上', async () => {
    const { env } = 环境();
    const r = await 读({ db: env.db, now: env.now }, {});
    expect(r.没接上).toEqual(['每晚流程', 'AI 返回的内容不能用']);
    expect(r.组们.map(g => g.来源)).toEqual(['维护', '维护']);
  });
});

describe('整理', () => {
  const 原始 = {
    天数: 7, 没接上: [],
    组们: [
      { 来源: '维护', 环节: '链接', 原因: '还没实现', 次数: 3, 最近: '2026-11-01T02:05:00.000Z', 对象们: [{ 名称: '甲', 网址: '' }, { 名称: '乙', 网址: '' }, { 名称: '丙', 网址: '' }, { 名称: '丁', 网址: '' }] },
      { 来源: '每晚流程', 环节: '04-extract', 原因: '读不到正文：404', 次数: 2, 最近: '2026-10-31T17:30:00Z', 对象们: [{ 名称: '某某杯通知', 网址: 'https://a.cn/1' }] },
      { 来源: 'AI 返回的内容不能用', 环节: '02-dedup · arbitrate', 原因: '漏了', 次数: 1, 最近: '2026-11-01T05:00:00.000Z', 对象们: [] },
    ],
  };
  test('最近的排前面；时间写北京时间；流程模块写中文名；各来源有几条', () => {
    const r = 整理(原始, {});
    expect(r.行们.map(g => [g.来源, g.环节, g.最近])).toEqual([
      ['AI 返回的内容不能用', '02 对比去重 · arbitrate', '2026-11-01 13:00'],
      ['维护', '链接', '2026-11-01 10:05'],
      ['每晚流程', '04 读详情和抽取', '2026-11-01 01:30'],
    ]);
    expect(r.来源们).toEqual([['全部', 3], ['每晚流程', 1], ['AI 返回的内容不能用', 1], ['维护', 1]]);
    expect(r.总次数).toBe(6);
  });
  test('按来源筛；涉及的对象先显示 3 个，其余写“等 N 个”', () => {
    const r = 整理(原始, { 来源: '维护' });
    expect(r.行们).toHaveLength(1);
    expect(r.行们[0]).toMatchObject({ 涉及: '甲、乙、丙 等 4 个' });
    expect(整理(原始, {}).行们[0].涉及).toBe('');
  });
});
