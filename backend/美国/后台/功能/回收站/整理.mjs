// 回收站 · 整理（纯计算）：快到期的排前面；刚做完的动作给一句提示。
const 提示文字 = {
  恢复比赛: r => `已恢复比赛 ${r.编号}，连同 ${r.届次} 届`,
  恢复届次: r => `已恢复届次 ${r.编号}`,
};

export function 整理(原始) {
  const 按到期 = (a, b) => a.还剩天数 - b.还剩天数;
  const 比赛们 = [...原始.比赛们].sort(按到期);
  const 届次们 = [...原始.届次们].sort(按到期);
  const 结果 = 原始.结果;
  return { 比赛们, 届次们, 总数: 比赛们.length + 届次们.length, 提示: 结果 ? 提示文字[结果.动作]?.(结果) || '' : '' };
}
