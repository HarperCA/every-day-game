// 回收站 · 呈现（浏览器里跑）：删除的比赛和单独删的届次，各自还剩几天；点“恢复”经 重新读取 把动作交给 数据库.mjs。
const 北京时间 = 时间 => new Date(new Date(时间).getTime() + 8 * 3600 * 1000).toISOString().slice(0, 16).replace('T', ' ');

export function 呈现(容器, 数据, { 重新读取, 建 }) {
  if (数据.提示) 容器.append(建('div', { class: '状态' }, 数据.提示));
  if (!数据.总数) {
    容器.append(建('div', { class: '状态' }, '回收站是空的。删除的比赛会在这里保留 30 天。'));
    return;
  }
  const 表 = (列, 行们) => 建('div', { class: '表格外框' }, 建('table', { class: '表格' },
    建('thead', {}, 建('tr', {}, 列.map(名 => 建('th', {}, 名)))),
    建('tbody', {}, 行们)));
  const 恢复 = (动作, 编号) => 建('button', { type: 'button', onclick: () => 重新读取({ 动作, 编号 }) }, '恢复');

  if (数据.比赛们.length) {
    容器.append(建('h3', {}, `删除的比赛（${数据.比赛们.length}）`), 表(['比赛', '连同届次', '删除时间', '删除人', '还剩', '操作'],
      数据.比赛们.map(c => 建('tr', {},
        建('td', {}, c.name), 建('td', {}, `${c.届次数} 届`), 建('td', {}, 北京时间(c.deleted_at)), 建('td', {}, c.deleted_by || ''),
        建('td', {}, `${c.还剩天数} 天`), 建('td', {}, 恢复('恢复比赛', c.id))))));
  }
  if (数据.届次们.length) {
    容器.append(建('h3', {}, `单独删的届次（${数据.届次们.length}）`), 表(['届次', '理由', '删除时间', '删除人', '还剩', '操作'],
      数据.届次们.map(e => 建('tr', {},
        建('td', {}, e.edition_name), 建('td', {}, e.理由 || ''), 建('td', {}, 北京时间(e.deleted_at)), 建('td', {}, e.deleted_by || ''),
        建('td', {}, `${e.还剩天数} 天`), 建('td', {}, 恢复('恢复届次', e.id))))));
  }
}
