// 呈现在浏览器里跑；这里用一个只记标签、属性、子元素的假 建 看画出来的结构（照 比赛管理 测试的做法）
function 假建() {
  return (标签, 属性 = {}, ...子) => {
    const 元素 = { 标签, 属性: {}, 子: [], append(...项们) { this.子.push(...项们.map(项 => (typeof 项 === 'object' && 项 ? 项 : String(项)))); } };
    for (const [名, 值] of Object.entries(属性)) if (值 != null && 值 !== false && !名.startsWith('on')) 元素.属性[名] = 值;
    元素.append(...子.flat(Infinity).filter(项 => 项 != null && 项 !== false));
    return 元素;
  };
}
const 文字之 = 节点 => (typeof 节点 === 'string' ? 节点 : 节点.子.map(文字之).join(''));
const 找元素 = (节点, 条件) => (typeof 节点 === 'string' ? [] : [...(条件(节点) ? [节点] : []), ...节点.子.flatMap(子 => 找元素(子, 条件))]);
const 有类 = 名 => 节点 => typeof 节点 !== 'string' && String(节点.属性.class || '').split(' ').includes(名);

describe('呈现：每一句下面是助手的回答', () => {
  function 画(人们) {
    const 建 = 假建();
    const 容器 = 建('div');
    const 条数 = 人们.reduce((和, p) => 和 + p.条数, 0);
    呈现(容器, 整理({ 没接上: false, 日期们: [{ 日期: '2026-11-12', 人数: 人们.length, 条数 }], 总天数: 1, 页: 1, 每页, 日期: '2026-11-12', 人们 }), { 重新读取: vi.fn(), 建 });
    return 容器;
  }

  test('一句一块：先是时间和输入，紧接着是这一句的回答（另一种样式），顺序和配对不乱', () => {
    const 容器 = 画([{ 账号: 'oAbCdE…9876', 条数: 2, 输入们: [
      { 时间: '00:05', 内容: '计算机有什么比赛', 回答: '有蓝桥杯\n还有 ACM', 状态: '' },
      { 时间: '10:30', 内容: '要团队赛', 回答: '那就 ACM', 状态: '' },
    ] }]);
    const 轮们 = 找元素(容器, 有类('聊天一轮'));
    expect(轮们.map(li => [li.标签, li.子.map(块 => 块.属性.class)])).toEqual([['li', ['聊天问', '聊天回答']], ['li', ['聊天问', '聊天回答']]]);
    expect(轮们.map(li => [文字之(找元素(li, 有类('聊天时间'))[0]), 文字之(找元素(li, 有类('聊天内容'))[0]), 文字之(找元素(li, 有类('聊天回答'))[0])])).toEqual([
      ['00:05', '计算机有什么比赛', '有蓝桥杯\n还有 ACM'],
      ['10:30', '要团队赛', '那就 ACM'],
    ]);
    expect(找元素(容器, 有类('聊天回答状态'))).toEqual([]);
    // 页面上的说明不再说“不显示助手的回答”
    expect(文字之(容器)).not.toContain('不显示助手的回答');
  });

  test('没有回答的：回答块标成“没有回答”，只写状态说明；被拦下的写状态，也照写回给用户的固定句子', () => {
    const 容器 = 画([{ 账号: 'oAbCdE…9876', 条数: 2, 输入们: [
      { 时间: '09:00', 内容: '超时那句', 回答: '', 状态: '没有回答（超时）' },
      { 时间: '09:01', 内容: '违规的话', 回答: '这个问题我没法回答。', 状态: '被内容安全拦下，回的是固定句子' },
    ] }]);
    const [超时, 拦下] = 找元素(容器, 有类('聊天回答'));
    expect(超时.属性.class).toBe('聊天回答 没有回答');
    expect(文字之(超时)).toBe('没有回答（超时）');
    expect(找元素(超时, 有类('聊天回答文字'))).toEqual([]);
    expect(拦下.属性.class).toBe('聊天回答');
    expect(文字之(找元素(拦下, 有类('聊天回答状态'))[0])).toBe('被内容安全拦下，回的是固定句子');
    expect(文字之(找元素(拦下, 有类('聊天回答文字'))[0])).toBe('这个问题我没法回答。');
  });
});
