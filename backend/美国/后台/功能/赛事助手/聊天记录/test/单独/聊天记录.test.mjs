import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { afterEach, describe, expect, test, vi } from 'vitest';
import { 打开问答记录 } from '../../../../../../赛事助手/问答记录.mjs';
import { 打开聊天记录, 聊天日期们, 某天聊天 } from '../../../../../../赛事助手/聊天记录.mjs';
import { 处理后台请求 } from '../../../../../接口.mjs';
import { 每页 } from '../../数据库.mjs';
import { 整理 } from '../../整理.mjs';
import { 呈现 } from '../../呈现.mjs';

const 临时 = [], 开着 = [];
afterEach(() => {
  while (开着.length) 开着.pop().关闭();
  while (临时.length) fs.rmSync(临时.pop(), { recursive: true, force: true });
});

const 甲 = 'oAbCdE1234567890xyzWXYZ9876';
const 乙 = 'oZZZZZ0000000000000000001111';
const 轮 = (id, openid, createdAt, message) => ({ id, openid, sessionId: 's1', createdAt, status: 'answered', message, reply: `助手回答${id}` });

// 照 服务.mjs 的接法：库文件不存在时是 null，接口交回空的
function 环境(轮们 = null) {
  const d = fs.mkdtempSync(path.join(os.tmpdir(), '后台聊天-')); 临时.push(d);
  const file = path.join(d, '问答记录.db');
  if (轮们) { const 写 = 打开问答记录(file); for (const t of 轮们) 写.存(t); 写.关闭(); }
  const 库 = 打开聊天记录(file); if (库) 开着.push(库);
  return { 聊天记录: { 日期们: 选项 => 聊天日期们(库, 选项), 某天: 日期 => 某天聊天(库, 日期) } };
}
const 有记录 = () => 环境([
  轮('t1', 甲, '2026-11-11T16:05:00.000Z', '计算机有什么比赛'),
  轮('t2', 乙, '2026-11-12T01:00:00.000Z', '数学建模什么时候报名'),
  轮('t3', 甲, '2026-11-12T02:30:00.000Z', '要团队赛'),
  轮('t4', 甲, '2026-11-11T15:59:00.000Z', '前一天晚上问的'),
  轮('t5', 乙, '2026-11-01T03:00:00.000Z', '十一月一号'),
]);
const 读 = (env, 参数 = {}) => 处理后台请求('聊天记录', 参数, env);

describe('取数据', () => {
  test('没指定日期时看最新的一天；交回这一页有记录的日子和这一天每个人的输入', async () => {
    const r = await 读(有记录());
    expect(r).toMatchObject({ 没接上: false, 总天数: 3, 页: 1, 每页, 日期: '2026-11-12' });
    expect(r.日期们.map(d => d.日期)).toEqual(['2026-11-12', '2026-11-11', '2026-11-01']);
    expect(r.人们.map(p => [p.账号, p.条数])).toEqual([['oAbCdE…9876', 2], ['oZZZZZ…1111', 1]]);
  });
  test('选日期看那一天', async () => {
    const r = await 读(有记录(), { 日期: '2026-11-11' });
    expect(r.日期).toBe('2026-11-11');
    expect(r.人们).toEqual([{ 账号: 'oAbCdE…9876', 条数: 1, 输入们: [{ 时间: '23:59', 内容: '前一天晚上问的', 回答: '助手回答t4', 状态: '' }] }]);
  });
  test('交给浏览器的数据里每句带着自己那一轮的回答；没有完整 openid', async () => {
    const r = await 读(有记录());
    expect(r.人们.map(p => p.输入们.map(句 => [句.内容, 句.回答]))).toEqual([
      [['计算机有什么比赛', '助手回答t1'], ['要团队赛', '助手回答t3']],
      [['数学建模什么时候报名', '助手回答t2']],
    ]);
    const 文字 = JSON.stringify(r);
    expect(文字).not.toContain(甲);
    expect(文字).not.toContain(乙);
  });
  test('库文件不存在：空的，不报错', async () => {
    expect(await 读(环境())).toMatchObject({ 没接上: false, 日期们: [], 总天数: 0, 日期: '', 人们: [] });
  });
  test('环境里没给 聊天记录：写明没接上，不报错', async () => {
    expect(await 读({})).toMatchObject({ 没接上: true, 日期们: [], 总天数: 0, 人们: [] });
  });
  test('日期写错了报错', async () => {
    await expect(读(有记录(), { 日期: '2026-13-40' })).rejects.toThrow(/日期/);
  });
});

