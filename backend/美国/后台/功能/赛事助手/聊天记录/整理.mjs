// 赛事助手聊天记录 · 整理（纯计算）：日期下拉框的选项（日期、星期、几人几句），这一天几人几句，翻页（新的日子在前）。
// 选的日子不在这一页里（用日期框跳过去的）也放进选项，排最前。
const 星期们 = ['周日', '周一', '周二', '周三', '周四', '周五', '周六'];
const 星期 = 日期 => (日期 ? 星期们[new Date(`${日期}T00:00:00Z`).getUTCDay()] : '');
const 标签 = (日期, 人数, 句数) => `${日期} ${星期(日期)} · ${人数} 人 ${句数} 句`;

export function 整理(原始) {
  const 人们 = 原始.人们 || [];
  const 当天句数 = 人们.reduce((和, p) => 和 + p.条数, 0);
  const 日期选项 = 原始.日期们.map(d => ({ 日期: d.日期, 标签: 标签(d.日期, d.人数, d.条数), 选中: d.日期 === 原始.日期 }));
  if (原始.日期 && !日期选项.some(o => o.选中)) 日期选项.unshift({ 日期: 原始.日期, 标签: 标签(原始.日期, 人们.length, 当天句数), 选中: true });
  const 共几页 = Math.max(1, Math.ceil(原始.总天数 / 原始.每页));
  return {
    没接上: Boolean(原始.没接上),
    日期: 原始.日期, 星期: 星期(原始.日期), 日期选项,
    人们, 当天人数: 人们.length, 当天句数,
    总天数: 原始.总天数, 页: 原始.页, 共几页, 有更新: 原始.页 > 1, 有更早: 原始.页 < 共几页,
  };
}
