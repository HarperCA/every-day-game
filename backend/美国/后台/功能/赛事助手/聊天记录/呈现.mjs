// 赛事助手聊天记录 · 呈现（浏览器里跑）：只看不改。换日期、翻页都经 重新读取 交给 数据库.mjs。
// 上面选日期（下拉框是这一页有记录的日子，日期框能跳到任意一天），更新/更早的日子翻页；下面这一天每人一块：账号、几句、每句的时间和内容，
// 每句下面紧跟助手这一轮的回答（2026-11-12 加；缩进、浅色底，样式在 框架.css）。回答全部显示、自动换行，不折叠：
// 助手回答最多 600 字（assistantCore 的 MAX_REPLY_CHARS），全文显示最多十几行，用不着点开收起的状态。
// 没有正常回答的在回答那里写状态说明（出错的只有说明，被拦下的说明 + 回给用户的固定句子）。
const 画回答 = (建, 句) => 建('div', { class: 句.回答 ? '聊天回答' : '聊天回答 没有回答', 'aria-label': '助手的回答' },
  句.状态 ? 建('span', { class: '聊天回答状态' }, 句.状态) : null,
  句.回答 ? 建('span', { class: '聊天回答文字' }, 句.回答) : null);
export function 呈现(容器, 数据, { 重新读取, 建 }) {
  if (数据.没接上) {
    容器.append(建('div', { class: '状态' }, '问答记录库没接上：后台服务没给 聊天记录。'));
    return;
  }
  if (!数据.总天数 && !数据.人们.length) {
    容器.append(建('div', { class: '状态' }, '还没有聊天记录。'));
    return;
  }
  const 看 = 日期 => 重新读取({ 页: 数据.页, 日期 });
  容器.append(建('div', { class: '工具栏' },
    建('select', { 'aria-label': '选日期', onchange: 事件 => 看(事件.target.value) },
      数据.日期选项.map(o => 建('option', { value: o.日期, selected: o.选中 }, o.标签))),
    建('input', { type: 'date', value: 数据.日期, 'aria-label': '跳到某一天', onchange: 事件 => { if (事件.target.value) 看(事件.target.value); } }),
    建('span', { class: '次要' }, `共 ${数据.总天数} 天有记录`)));

  容器.append(建('p', { class: '标签说明' }, `${数据.日期} ${数据.星期}：${数据.当天人数} 人，${数据.当天句数} 句。每句下面是助手的回答；账号中间打了码。`));
  if (!数据.人们.length) 容器.append(建('div', { class: '状态' }, '这一天没有聊天记录。'));
  else {
    容器.append(建('div', { class: '聊天人们' }, 数据.人们.map(p => 建('section', { class: '聊天人' },
      建('div', { class: '聊天人头' }, 建('span', { class: '聊天账号' }, p.账号), 建('span', { class: '次要' }, `${p.条数} 句`)),
      建('ol', { class: '聊天输入们' }, p.输入们.map(句 => 建('li', { class: '聊天一轮' },
        建('div', { class: '聊天问' }, 建('span', { class: '聊天时间' }, 句.时间), 建('span', { class: '聊天内容' }, 句.内容)),
        画回答(建, 句))))))));
  }

  if (数据.共几页 > 1) {
    容器.append(建('div', { class: '工具栏 翻页' },
      建('button', { type: 'button', disabled: !数据.有更新, onclick: () => 重新读取({ 页: 数据.页 - 1 }) }, '更新的日子'),
      建('span', {}, `第 ${数据.页} / ${数据.共几页} 页`),
      建('button', { type: 'button', disabled: !数据.有更早, onclick: () => 重新读取({ 页: 数据.页 + 1 }) }, '更早的日子')));
  }
}
