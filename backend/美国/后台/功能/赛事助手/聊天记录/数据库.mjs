// 赛事助手聊天记录 · 取数据（美国服务器上跑）：只看不改（2026-11-12 用户定）。
// 不自己读问答记录的表，只调环境里的 聊天记录（服务.mjs 接到 赛事助手/聊天记录.mjs 的接口，问答记录库只读打开）：
//   聊天记录.日期们({ 页, 每页 }) → { 日期们: [{ 日期, 人数, 条数 }], 总天数, 页, 每页 }
//   聊天记录.某天(日期) → [{ 账号（已打码）, 条数, 输入们: [{ 时间, 内容, 回答, 状态 }] }]
// 交回打码账号、用户输入的内容和助手这一轮的回答（出错没回的回答是 ''，状态写原因），没有完整 openid。
// 库文件不存在时接口交回空的；环境里没给就写明没接上。
//
//   取({ 页, 日期 }, { 聊天记录 })   没给日期时看这一页最新的一天
export const 每页 = 30;

export async function 取({ 页 = 1, 日期 = '' } = {}, { 聊天记录 } = {}) {
  if (!聊天记录) return { 没接上: true, 日期们: [], 总天数: 0, 页: 1, 每页, 日期: '', 人们: [] };
  const 汇总 = await 聊天记录.日期们({ 页, 每页 });
  const 选中 = String(日期 || '') || 汇总.日期们[0]?.日期 || '';
  const 人们 = 选中 ? await 聊天记录.某天(选中) : [];
  return { 没接上: false, ...汇总, 日期: 选中, 人们 };
}
