// 总览 · 呈现（浏览器里跑）：切换维度的按钮、环形图（中间总数、外圈分类、旁边说明）、数据时间。
import { 画环形图 } from '../../框架/组件/环形图.mjs';

export function 呈现(容器, 数据, { 条件, 改条件, 建 }) {
  容器.append(建('div', { class: '工具栏', role: 'group', 'aria-label': '按什么分' },
    数据.维度们.map(名 => 建('button', {
      type: 'button', class: 名 === 条件.维度 ? '切换 选中' : '切换', 'aria-pressed': String(名 === 条件.维度),
      onclick: () => 改条件({ 维度: 名 }),
    }, 名))));
  const 图区 = 建('div');
  容器.append(图区);
  画环形图(图区, { 总数: 数据.总数, 单位: 数据.单位, 分组: 数据.分组, 标题: '比赛库总数' });
  容器.append(建('p', { class: '标签说明' },
    数据.示例 ? 建('span', { class: '示例标记', title: '比赛库还没建，用的是快照' }, '示例数据') : null,
    ` 数据时间：${数据.时间}`));
}
