// 总览 · 整理（纯计算）：按选中的维度分组计数，每组配上中文名和说明，按数量从多到少排。
export const 维度们 = ['按状态', '按级别'];

const 状态说明 = {
  已归档: '报名截止后程序自动归档的届次；小程序里排在最后，显示为已结束',
  已发布: '审核通过、小程序里正在显示的届次',
  待人工审核: '机器拿不准、等人定的届次，每条都写了理由；小程序看不到',
};
const 级别说明 = {
  国家级: '后台记录的级别为国家级',
  '省级/区域级': '后台记录的级别为省级或区域级',
  '其他/未明确': '来源里没写明级别，或还没判定',
  国际级: '后台记录的级别为国际级',
};

function 计数(值们) {
  const 数 = new Map();
  for (const 值 of 值们) 数.set(值, (数.get(值) || 0) + 1);
  return 数;
}

export function 整理(原始, { 维度 = '按状态' } = {}) {
  if (!维度们.includes(维度)) throw new Error(`没有这个维度：${维度}`);
  const 数 = 原始.示例
    ? new Map(Object.entries(原始.快照[维度]))
    : 计数(原始.届次们.map(行 => (维度 === '按状态' ? 行.状态 : 行.级别 || '其他/未明确')));
  const 分组 = [...数].map(([键, 数量]) => {
    if (维度 === '按状态') {
      return { 名称: 键, 数量, 说明: 状态说明[键] || '' };
    }
    return { 名称: 键, 数量, 说明: 级别说明[键] || '' };
  }).sort((a, b) => b.数量 - a.数量);
  return {
    维度, 维度们, 分组, 单位: '届',
    总数: 分组.reduce((和, 组) => 和 + 组.数量, 0),
    示例: 原始.示例, 时间: 原始.示例 ? 原始.快照.时间 : 原始.时间,
  };
}
