// 校赛审核 · 整理（纯计算）：管理员申请、校赛各一张表，待审核在前、同一类里新提交的在前；按状态给出能做的操作；
// 视图“待审核”只留待审核的。账号编号只露最后 6 位。能做的操作和 数据库.mjs 的规矩一致（服务器那边会再查一遍）。
//   整理(原始, { 视图 }) → { 申请们, 校赛们, 数量: { 申请: { 全部, 待审核 }, 校赛: { 全部, 待审核 } }, 视图, 视图们, 结果, 接好了 }
export const 视图们 = ['全部', '待审核'];
const 申请能做 = { 待审核: ['通过', '拒绝'] };
const 校赛能做 = { 待审核: ['通过', '拒绝'], 已发布: ['下架'] };

const 排好 = 行们 => [...行们].sort((a, b) =>
  Number(b.status === '待审核') - Number(a.status === '待审核') || String(b.created_at).localeCompare(String(a.created_at)));
const 数 = 行们 => ({ 全部: 行们.length, 待审核: 行们.filter(x => x.status === '待审核').length });

export function 整理(原始, 条件 = {}) {
  if (!原始?.接好了) return { 接好了: false, 来源: 原始?.来源 };
  const 视图 = 视图们.includes(条件.视图) ? 条件.视图 : '全部';
  const 留下 = x => 视图 === '全部' || x.status === '待审核';
  const 申请们 = 排好(原始.申请们 || []).filter(留下).map(x => ({ ...x, 能做: 申请能做[x.status] || [], 账号: `…${String(x.user || '').slice(-6)}` }));
  const 校赛们 = 排好(原始.校赛们 || []).filter(留下).map(x => ({ ...x, 能做: 校赛能做[x.status] || [] }));
  return { 申请们, 校赛们, 数量: { 申请: 数(原始.申请们 || []), 校赛: 数(原始.校赛们 || []) }, 视图, 视图们, 结果: 原始.结果, 接好了: true };
}
