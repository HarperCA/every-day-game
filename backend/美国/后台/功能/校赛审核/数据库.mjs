// 校赛审核 · 取数据和操作（美国服务器上跑，2026-11-08 粗版本）：用户定“校赛在美国审核通过才能在小程序发布”。
// 列表读北京同步到美国的用户副本：school_admin（校赛管理员申请）、school_contest（校赛）；学生名单不传美国，这里也没有。
// 审核结果（status、review_note）经 环境.回传 写回北京正本（沟通/审核结果回传，种类 '校赛管理员'、'校赛'），比赛库留一条后台记录。
//   管理员申请：待审核的 通过 → 已通过、拒绝 → 已拒绝（拒绝要写说明）
//   校赛：待审核的 通过 → 已发布、拒绝 → 已拒绝；已发布的 下架 → 已下架（拒绝、下架要写说明）
//   说明写进 review_note 传回北京（负责人在小程序里看得到）；后台记录里也留一份。
//   取({ 动作: '审核申请' | '审核校赛', 编号, 决定, 说明, 读到的更新时间 }, { db, 用户副本库, 回传 }) → { 申请们, 校赛们, 来源, 接好了, 结果 }
// 以后再做：内容安全检查、审核后通知负责人、撤销已通过的管理员。
import { 用户副本, 用户反馈 } from '../../../db/index.mjs';

const 来源 = '北京同步来的校赛管理员申请和校赛（用户副本的 school_admin、school_contest）';
// 每种审核：用户副本里哪张表、回传的种类、每个决定在什么状态下能做、改成什么、要不要写说明
const 审核们 = {
  审核申请: {
    表: 'school_admin', 种类: '校赛管理员', 名: '管理员申请', 记录: '审核校赛管理员',
    决定们: { 通过: { 从: ['待审核'], 改成: '已通过' }, 拒绝: { 从: ['待审核'], 改成: '已拒绝', 要说明: true } },
    详情: 行 => ({ 学校: 行.school, 姓名: 行.real_name }),
  },
  审核校赛: {
    表: 'school_contest', 种类: '校赛', 名: '校赛', 记录: '审核校赛',
    决定们: { 通过: { 从: ['待审核'], 改成: '已发布' }, 拒绝: { 从: ['待审核'], 改成: '已拒绝', 要说明: true }, 下架: { 从: ['已发布'], 改成: '已下架', 要说明: true } },
    详情: 行 => ({ 学校: 行.school, 标题: 行.title }),
  },
};
const 中文 = {
  feedback_conflict: '这一条已被其他管理员处理过，请刷新后再看。',
  school_review_not_ready: '北京还没上线校赛审核（副数据库的校赛操作还没部署），结果写不回去。',
  review_note_required: '拒绝、下架要写明原因。',
  invalid_school_status: '北京不认这个状态。',
};
const 换中文 = message => 中文[message] || (/_not_found$/.test(message) ? '北京找不到这一条（可能已被删除），刷新看看。' : message);

async function 审核({ 动作, 编号, 决定, 说明 = '', 读到的更新时间 }, { db, 用户副本库, 回传 }) {
  const 种 = 审核们[动作];
  const 行 = 用户副本.一条(用户副本库, 种.表, 编号);
  if (!行) throw new Error(`找不到这条${种.名}（刷新看看）`);
  const 规矩 = Object.hasOwn(种.决定们, 决定) ? 种.决定们[决定] : null;
  if (!规矩) throw new Error(`${种.名}不能“${决定}”`);
  if (!规矩.从.includes(行.status)) throw new Error(`这条${种.名}现在是“${行.status}”，不能${决定}`);
  const 写的 = String(说明 ?? '').trim();
  if (规矩.要说明 && !写的) throw new Error(`${决定}要写明原因`);
  try {
    await 回传({ 种类: 种.种类, 编号, 改动: { status: 规矩.改成, review_note: 写的 }, 读到的更新时间 });
  } catch (错误) {
    throw new Error(换中文(String(错误?.message || 错误)));
  }
  用户反馈.记处理(db, { 动作: 种.记录, 表: 种.表, 编号, 详情: { ...种.详情(行), 结果: 规矩.改成, 说明: 写的 } });
  return `${种.名}已改成“${规矩.改成}”。`;
}

export async function 取(参数 = {}, 环境 = {}) {
  if (!环境.用户副本库) return { 申请们: [], 校赛们: [], 来源, 接好了: false };
  const 结果 = Object.hasOwn(审核们, 参数.动作) ? await 审核(参数, 环境) : null;
  return {
    申请们: 用户副本.列出(环境.用户副本库, 'school_admin'),
    校赛们: 用户副本.列出(环境.用户副本库, 'school_contest'),
    来源, 接好了: true, 结果,
  };
}
