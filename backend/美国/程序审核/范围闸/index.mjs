// 第 2 关 范围闸：是不是一场具体的、大学生能参加的专业比赛。只看字段，不调接口。
// 搬自 adminData/competitionScope.js 的 classifyCompetitionScope、isClearlyOutOfScope（规则不变，字段改成新库的名字）。
// 资料多少都能调：只有标题时，照样判得出“不收”（中小学、校赛、初赛、目录、喜报、不像一场比赛）；
// 要看参赛对象、专业的部分没有资料就交回“待定”，等读完详情再调一次（旧代码搜索层、入库、发布前都调它）。
//
//   查范围(记录) → { 结果: '通过' | '待定' | '不收', 原因 }   看 name、edition_name、participants、eligibility、format_and_rules、professions、parent_id、curation_list
//   明显不是大学生(记录) → true/false                          中小学、青少年、兴趣体育
import { 查标题, 是通知标题, 不是比赛的标题 } from '../标题闸/index.mjs';

// 【已冻结，不要再往里加词】（旧注释）：这条是 2026-09 “发现一条垃圾补一个词”攒出来的，补不完，也容易误伤。
// 新出现的“不是大学生赛事”改由看参赛对象字段的实际内容判断；这里只留中小学、青少年这类确定的受众错配和历史遗留的具体赛事名。
const 明显不收 = /中小学|小学生|初中生|高中生|青少年|少年儿童|全国少年|奔跑吧[·•]少年|全民健身|男子飞盘|帕克球|数独公开赛|单板滑雪|健身气功|柔术U系列|魔方运动|车辆模型（攀爬|仿真模型（静态|无线电测向|研究生男子篮球联赛|音乐节大学生歌手大赛|咖啡师职业技能大赛/;

// 参赛对象里能确认“大学生可以参加”的写法。只在参赛对象上匹配，不看标题；匹配词根，“本科学生”“高等学校”也认得
export const 大学生对象 = /大学生|本科|专科|研究生|硕士|博士|高职|高专|高校|高等(?:学校|院校|教育)|在校(?:生|学生|大学生)|在读(?:生|学生)|学籍|MBA|MPA/i;

const 专业词 = /学科|专业|学术|科研|科技|技术|技能|设计|工程|创新|创业|数学|统计|物理|化学|化工|生物|医学|生命|计算机|程序|软件|算法|信息|数据|人工智能|AI|电子|集成电路|芯片|机械|自动化|机器人|智能汽车|建筑|结构|测绘|能源|环境|农业|食品|材料|交通|物流|供应链|商业|商务|经济|金融|财会|会计|审计|税务|管理|法律|法学|外语|英语|翻译|语言|汉语|汉字|普通话|写作|数字媒体|包装|广告|文献|检索|ICPC|CCSP/i;

const 对象文字 = 记录 => `${记录.participants || ''} ${记录.eligibility || ''}`.trim();

export function 明显不是大学生(记录 = {}) {
  const title = String(记录.name || '').normalize('NFKC').trim();
  if (/奔跑吧[\s,，·•、]*少年/.test(title) || /车辆模型\(攀爬|仿真模型\(静态/.test(title) || 明显不收.test(title)) return true;
  const 对象 = 对象文字(记录);
  return /中小学|小学生|初中生|高中生|少年儿童/.test(对象) && !/大学生|本科生|研究生|高校/.test(对象);
}

export function 查范围(记录 = {}) {
  const title = String(记录.name || '').normalize('NFKC')
    .replace(/&#(?:x([0-9a-f]+)|(\d+));/gi, (_, hex, dec) => String.fromCodePoint(parseInt(hex || dec, hex ? 16 : 10))).trim();
  const 不收 = 原因 => ({ 结果: '不收', 原因 });
  const 待定 = 原因 => ({ 结果: '待定', 原因 });
  if (!title) return 不收('缺少赛事名称');
  const 标题 = 查标题({ ...记录, name: title });
  if (标题.结果 !== '通过') return 不收(标题.原因);
  if (明显不是大学生({ ...记录, name: title })) return 不收('非大学生专业赛事');
  // 校赛、院赛是上级比赛的选拔环节；挂了上级比赛（parent_id）才能作为子记录
  if (/校级(?:选拔赛|初赛)|校内(?:选拔赛|初赛|赛)|院级(?:选拔赛|初赛)|学院选拔赛/.test(title) && !记录.parent_id) return 不收('校赛或院赛是上级赛事的下级选拔，必须关联父赛事，不得作为独立赛事');
  // 名称带“（初赛）”这类阶段标注的，是某场比赛的一个阶段（2026-09-30 用户确认）
  if (/[（(]\s*(?:初赛|复赛|预赛|半决赛|决赛)(?:阶段)?\s*[）)]/.test(title) && !记录.parent_id) return 不收('名称标注了比赛阶段（如“（初赛）”），是某场比赛的一个阶段，不单独收录');
  if (是通知标题(title) || 不是比赛的标题(title) || /通知(?:[-_｜|]|$)/.test(title)) return 不收('通知、栏目或目录线索，需要追溯比赛本身');
  if (/目录|清单|汇总|全梳理|资讯速递|参赛指南|赛题分析|报名表|模拟考场|错题重练|群众文艺|文化艺术季|音乐节|作品评选/.test(title)) return 不收('目录、资料或兴趣文化活动，不是专业赛事');
  if (/喜报|学子获|获奖名单|晋级.*名单|斩获|创佳绩|(?:学院|大学|学校|团队|学生).*获.*(?:等奖|金奖|银奖|铜奖)|决赛.*(?:举行|闭幕|落幕|收官)/.test(title)) return 不收('赛后报道或结果公示，不是赛事条目');
  // “赛”结尾是中文赛事命名的实际标志；来自权威榜单的，以“奖”“展”“展示”“活动”结尾的也算（2026-10-03 用户确认，只对榜单来源放宽）
  const 榜单奖项 = Boolean(记录.curation_list) && /(?:奖|展|展示|活动)[\s)）\]】]*$/.test(title);
  if (!榜单奖项 && !/竞赛|大赛|挑战赛|锦标赛|联赛|黑客松|奥林匹克|比赛|挑战|赛[\s)）\]】]*$|ICPC|CCSP|RoboMaster|ROBOCON/i.test(title)) return 不收('标题不是一场具体比赛');

  // 有证据看证据，没证据才退回标题（旧注释：标题里碰巧有个词不能顶替真实证据，也不能否决证据齐全的真比赛）
  const 对象 = 对象文字(记录);
  if (对象) {
    if (!大学生对象.test(对象)) return 待定('参赛对象未表明大学生可以参加');
  } else if (!大学生对象.test(title) && !/ICPC|CCSP/i.test(title)) {
    return 待定('缺少大学生参赛资格依据');
  }
  // 专业分类是人工或 AI 带证据判定的，本身就是专业关联的依据；没人判过才退回标题、赛制词表粗筛
  if (!记录.professions?.length && !专业词.test(`${title} ${记录.format_and_rules || ''}`)) return 待定('缺少专业学习或专业技能关联依据');
  return { 结果: '通过', 原因: '具备具体赛事、大学生范围与专业关联依据' };
}
