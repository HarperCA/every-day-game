// 名称规范化：去掉年份、第几届、引号括号空白，结尾的竞赛/大赛/比赛/挑战赛，用来判断两个名字说的是不是同一个比赛。
// 同旧 search-plan.mjs 的 normalizeName。02 对比去重、06 入库（对照主库、比赛编号）都用。
export function 规范名称(name) {
  return String(name || '')
    .replace(/(?:19|20)\d{2}(?:[—–~～至-](?:19|20)\d{2})?年?/g, '')
    .replace(/第[零〇一二三四五六七八九十百千万两\d]+届/g, '')
    .replace(/[“”"'‘’「」《》()（）\s·•・]/g, '')
    .replace(/(?:竞赛|大赛|比赛|挑战赛)$/, '');
}
