// 北京兜底（2026-11-09 用户定）：美国读网页、取源码时，如果是网络问题读不到（国内政府、学校网站从美国访问不稳），改请北京代读一次。
//
//   带北京兜底({ 读网页, 取源码, 代读 }) → { 读网页, 取源码 }   参数和交回的格式都和原来的一样
//     代读(网址, { 方式: '网页' | '源码', etag, 最后修改, signal }) 是 沟通/代读网页/美国端.mjs 的 代读（地址、秘钥由调用方先绑好）
//   是网络问题(结果) → true / false
//
// 算网络问题的：超时；网络错误（连接被重置、连不上、域名解析失败、证书错误都在这里，下载那一步写成“fetch failed（错误码）”）；
//   HTTP错误里对方回 403 或 5xx（有的网站挡国外 IP）。
// 不算的（不改走北京）：成功、没更新(304)、404 等其余 HTTP 错误、跳转太多、太大、不支持的类型、robots 不允许、内网地址、
//   正文太短、读不出文字、内部错误——这些换个地方读结果也一样。调用方已经喊停（signal 已中止）也不请北京。
// 北京给了不是网络问题的答复（成功、没更新、正文太短、404……）就用北京的，结果里加 经北京: true（维护过程里能看出来）；
// 北京也是网络问题、或者代读失败，就交回原来的失败结果，error 后面补一句“北京也没读到：…”。代读出错也不往外抛。
// 无头浏览器不经北京（北京没装浏览器）。
const 网络类状态 = new Set(['超时', '网络错误']);

export function 是网络问题(结果) {
  if (!结果 || typeof 结果 !== 'object') return false;
  if (网络类状态.has(结果.status)) return true;
  return 结果.status === 'HTTP错误' && (结果.httpStatus === 403 || (结果.httpStatus >= 500 && 结果.httpStatus <= 599));
}

export function 带北京兜底({ 读网页, 取源码, 代读 }) {
  const 包 = (读, 方式) => async (网址, 选项 = {}) => {
    const 原 = await 读(网址, 选项);
    if (!是网络问题(原) || 选项.signal?.aborted) return 原;
    let 北;
    try {
      北 = await 代读(网址, { 方式, signal: 选项.signal, ...(方式 === '源码' ? { etag: 选项.etag ?? null, 最后修改: 选项.最后修改 ?? null } : {}) });
    } catch (error) {
      北 = { status: '网络错误', error: String(error?.message || error).slice(0, 200) };
    }
    if (北 && typeof 北.status === 'string' && !是网络问题(北)) return { ...北, 经北京: true };
    return { ...原, error: `${原.error}；北京也没读到：${北?.error || 北?.status || '没交回结果'}` };
  };
  return { 读网页: 包(读网页, '网页'), 取源码: 包(取源码, '源码') };
}
