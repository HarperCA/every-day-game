// 写爬虫脚本（2026-11-08 用户定）：AI 看程序压缩过的官网页面，写一串步骤（打开、等待、点击、取列表）；程序按步骤试跑，最多 3 轮。
// 用途 crawl_script：线上是 Codex；本地试跑时由试跑程序把它换成 Kimi。AI 只交回步骤，程序照着做，不运行 AI 写的代码。
//
//   写脚本(比赛, { ai, 取源码, 浏览器, 起点网址, 要浏览器, 原因, 旧脚本, 最多轮 })
//     → { 结果: '写好' | '写不出', 脚本: { 列表页, 步骤, 要浏览器, 写的人, 提示版本 }, 试跑, 轮们: [{ 轮, 状态, 说明 }], 用量, 原因 }
//   每一轮 AI 交回三种之一：
//     要看：最多 3 个网址（页面里出现过的），程序打开后下一轮给它；
//     规则：程序校验步骤格式（db 的 爬虫脚本.校验步骤）、试跑（爬虫/执行），取到条目、并且有条目带比赛名或者至少 3 条就算写好；
//           不合格把原因和列表页结构告诉它，下一轮再改；
//     做不到：还没用浏览器、又有浏览器时，改用浏览器打开后的页面再问；否则写不出。
//   用浏览器：调用方要求（旧脚本爬不到新通知时重写，用户定用无头浏览器），或者直接下载只拿到空壳页（看得到的字不到 200）。
//   AI 出错（额度用完、对方出错）照样抛出，交给调用方顺延；格式不对（包括 ai.chat 抛 kind 为“格式不对”的错）算这一轮没按格式回答，告诉下一轮。
//   浏览器起不来（新页面抛错）当这一页打不开，原因以“浏览器打不开”开头；试跑时起不来算试跑不合格。
import { 爬虫脚本 } from '../../index.mjs';
import { 名称写法, 规范名 } from '../找官网/核实.mjs';
import { 执行脚本 } from './执行.mjs';
import { 压缩, 文字量 } from './压缩.mjs';

export const 提问版本 = 'crawl-script-v1';
const 空壳字数 = 200;
const 最多要看 = 3;

// Codex 的 --output-schema 要求每个字段都写出来：用不到的填空字符串、毫秒填 0，程序收到后去掉
const 一步 = { type: 'object', additionalProperties: false, required: ['动作', '网址', '选择器', '毫秒', '条目', '标题', '链接', '日期'], properties: {
  动作: { type: 'string', enum: 爬虫脚本.动作们 }, 网址: { type: 'string' }, 选择器: { type: 'string' }, 毫秒: { type: 'integer' },
  条目: { type: 'string' }, 标题: { type: 'string' }, 链接: { type: 'string' }, 日期: { type: 'string' } } };
export const 交回格式 = { type: 'object', additionalProperties: false, required: ['状态', '要看', '列表页', '步骤', '说明'], properties: {
  状态: { type: 'string', enum: ['规则', '要看', '做不到'] }, 要看: { type: 'array', items: { type: 'string' } }, 列表页: { type: 'string' },
  步骤: { type: 'array', items: 一步 }, 说明: { type: 'string' } } };

const 各动作的字段 = { 打开: ['网址'], 等待: ['选择器', '毫秒'], 点击: ['选择器'], 取列表: ['条目', '标题', '链接', '日期'] };
function 整理步骤(步骤 = []) {
  return (Array.isArray(步骤) ? 步骤 : []).map(步 => {
    const 留 = { 动作: 步?.动作 };
    for (const 名 of 各动作的字段[步?.动作] || []) {
      const 值 = 步[名];
      if (名 === '毫秒' ? Number.isInteger(值) && 值 > 0 : typeof 值 === 'string' && 值.trim()) 留[名] = 名 === '毫秒' ? 值 : 值.trim();
    }
    if (留.动作 === '等待' && 留.选择器) delete 留.毫秒;
    return 留;
  });
}

function 合格(试跑, 比赛) {
  if (试跑.状态 !== '成功') return 试跑.错误 || '试跑失败';
  const 名们 = 名称写法(比赛);
  if (试跑.条目们.some(x => 名们.some(名 => 规范名(x.标题).includes(名))) || 试跑.条目们.length >= 3) return '';
  return `只取到 ${试跑.条目们.length} 条，标题里都没有比赛名：${试跑.条目们.map(x => x.标题).join('；').slice(0, 200)}`;
}

function 题目(比赛, { 起点网址, 原因, 旧脚本, 用浏览器, 反馈, 资料 }) {
  return [
    `比赛：${比赛.name}${比赛.aliases?.length ? `（别名：${比赛.aliases.join('、')}）` : ''}。官网：${起点网址}`,
    '任务：给这个官网写一份爬虫脚本，让程序以后定期读“发布这个比赛通知的列表页”，取出每条通知的标题、链接、日期，用来发现新一届的报名通知。',
    '脚本是一串步骤，动作只有四种：',
    '- 打开：网址；',
    '- 等待：选择器（等它出现）或毫秒（最多 15000）；',
    '- 点击：选择器（只有无头浏览器能点）；',
    '- 取列表：条目（每条通知的 CSS 选择器），标题、链接、日期（相对条目的 CSS 选择器，留空表示用条目里第一个链接的文字和地址、没有日期）。',
    '最后一步必须是取列表。不需要的字段填空字符串，毫秒填 0。',
    '列表页优先选最可能出现这个比赛通知的栏目（通知公告、赛事通知、新闻动态等），不要选首页轮播。',
    ...(原因 ? [`这次重写的原因：${原因}`] : []),
    ...(旧脚本 ? [`旧脚本（列表页 ${旧脚本.列表页}）：${JSON.stringify(旧脚本.步骤)}`] : []),
    '只根据下面给的页面结构作答，不要编造页面里没有的网址和选择器。',
    `需要先看别的页（比如栏目页），状态填“要看”，要看里写最多 ${最多要看} 个网址（必须是页面里出现过的链接）；能写就填“规则”，列表页填通知列表页的网址；实在写不出填“做不到”，说明里写原因。`,
    用浏览器 ? '下面的页面是无头浏览器打开（脚本执行完）后的样子，脚本会用无头浏览器执行。' : '下面的页面是直接下载的源码，脚本不用浏览器执行（不能点击）。',
    ...(反馈 ? ['', `上一轮的结果：${反馈}`] : []),
    '',
    资料,
    '',
    '只回 JSON。',
  ].join('\n');
}

export async function 写脚本(比赛, { ai, 取源码, 浏览器 = null, 起点网址, 要浏览器 = false, 原因 = '', 旧脚本 = null, 最多轮 = 3 } = {}) {
  const 轮们 = [];
  const 用量 = { tokensIn: 0, tokensOut: 0 };
  let 用浏览器 = Boolean(要浏览器 && 浏览器);
  const 写不出 = 原因 => ({ 结果: '写不出', 脚本: null, 试跑: null, 轮们, 用量, 原因 });

  // 打开一页，交回源码；用浏览器时读脚本执行完的页面
  async function 看(网址) {
    if (用浏览器) {
      // 浏览器起不来当这一页打不开；原因以“浏览器打不开”开头，调用方能看出是环境问题
      let 页, 关;
      try { ({ 页, 关 } = await 浏览器.新页面()); } catch (error) { return { ok: false, 原因: `浏览器打不开：${String(error?.message || error).split('\n')[0].slice(0, 120)}` }; }
      try { await 页.打开(网址); return { ok: true, html: await 页.源码(), 网址: 页.网址() || 网址 }; }
      catch (error) { return { ok: false, 原因: String(error?.message || error).split('\n')[0].slice(0, 120) }; }
      finally { await 关(); }
    }
    const 页 = await 取源码(网址);
    return 页.status === '成功' ? { ok: true, html: 页.html, 网址: 页.finalUrl || 网址 } : { ok: false, 原因: `${页.status}${页.error ? ` ${页.error}` : ''}` };
  }
  const 写成资料 = (标签, 网址, 页) => `【${标签} ${网址}】\n${页.ok ? 压缩(页.html, 页.网址) : `打不开：${页.原因}`}`;

  let 起点 = await 看(起点网址);
  if (起点.ok && !用浏览器 && 浏览器 && 文字量(起点.html) < 空壳字数) { 用浏览器 = true; 起点 = await 看(起点网址); }
  if (!起点.ok) return 写不出(`起点打不开：${起点.原因}`);
  let 资料 = 写成资料('首页', 起点网址, 起点);
  let 反馈 = '';

  for (let 轮 = 1; 轮 <= 最多轮; 轮 += 1) {
    let 回;
    try {
      回 = await ai.chat({ purpose: 'crawl_script', messages: [{ role: 'user', content: 题目(比赛, { 起点网址, 原因, 旧脚本, 用浏览器, 反馈, 资料 }) }], json: true, schema: 交回格式, promptVersion: 提问版本 });
    } catch (错误) {
      // 交回的 JSON 解析不出来：算这一轮没按格式回答，告诉下一轮；额度用完、对方出错等照样抛出
      if (错误?.kind !== '格式不对') throw 错误;
      轮们.push({ 轮, 状态: '没按格式', 说明: `没按格式回答：${String(错误.message || '').slice(0, 120)}` });
      反馈 = '上一轮没按格式回答（交回的不是要求的 JSON）。只回 JSON，状态只能是 规则、要看、做不到。';
      continue;
    }
    用量.tokensIn += 回.usage?.tokensIn || 0;
    用量.tokensOut += 回.usage?.tokensOut || 0;
    const 答 = 回.data || {};
    const 记 = 说明 => 轮们.push({ 轮, 状态: 答.状态 || '没按格式', 说明 });

    if (答.状态 === '要看') {
      const 网址们 = (答.要看 || []).filter(u => /^https?:\/\//i.test(String(u))).slice(0, 最多要看);
      记(`要看 ${网址们.join('、') || '（没给网址）'}`);
      const 页们 = await Promise.all(网址们.map(async u => 写成资料('页面', u, await 看(u))));
      资料 = 页们.join('\n\n') || 资料;
      反馈 = '你要看的页面在下面（首页上一轮已经看过）。';
      continue;
    }
    if (答.状态 === '做不到') {
      记(`做不到：${答.说明 || ''}`);
      if (!用浏览器 && 浏览器) {
        用浏览器 = true;
        起点 = await 看(起点网址);
        if (!起点.ok) return 写不出(`做不到：${答.说明 || ''}；浏览器也打不开起点：${起点.原因}`);
        资料 = 写成资料('首页', 起点网址, 起点);
        反馈 = `你说做不到（${答.说明 || ''}），现在给的是无头浏览器打开后的页面。`;
        continue;
      }
      return 写不出(`做不到：${答.说明 || ''}`);
    }
    if (答.状态 !== '规则') { 记('没按格式回答'); 反馈 = '上一轮没按格式回答，状态只能是 规则、要看、做不到。'; continue; }

    const 步骤 = 整理步骤(答.步骤);
    const 列表页 = /^https?:\/\//i.test(String(答.列表页 || '')) ? 答.列表页 : (步骤.find(步 => 步.动作 === '打开')?.网址 || 起点网址);
    const 脚本 = { 列表页, 步骤, 要浏览器: 用浏览器 || 步骤.some(步 => 步.动作 === '点击'), 写的人: 回.provider ?? null, 提示版本: 提问版本 };
    try { 爬虫脚本.校验步骤(步骤); } catch (error) {
      记(`步骤格式不对：${error.message}`);
      反馈 = `步骤格式不对：${error.message}。请改。`;
      continue;
    }
    if (脚本.要浏览器 && !浏览器) { 记('脚本要点击，但现在没有浏览器'); 反馈 = '现在只能直接下载源码、不能点击，请写不用点击的脚本。'; continue; }
    const 试跑 = await 执行脚本(脚本, { 取源码, 浏览器 });
    const 不合格 = 合格(试跑, 比赛);
    if (!不合格) { 记(`试跑取到 ${试跑.条目们.length} 条`); return { 结果: '写好', 脚本, 试跑, 轮们, 用量, 原因: '' }; }
    记(`试跑不合格：${不合格}`);
    const 列表 = await 看(列表页);
    资料 = 写成资料('列表页', 列表页, 列表);
    反馈 = `按你的脚本试跑：${不合格}。请改脚本。`;
  }
  return 写不出(`${最多轮} 轮都没写出能用的脚本：${轮们.at(-1)?.说明 || ''}`);
}
