const 读到内容 = new Set(['成功', '正文太短']);   // 读网页的这两种状态算读到了内容，其余（超时、网络错误、HTTP错误……）算打不开
// 条目日期变成可比的数（2026-10-01、2026/10/1、2026.10.1、2026年10月1日都认）；没有日期给 null
const 日期值 = 日期 => { const m = String(日期 || '').match(/((?:19|20)\d{2})\D{1,2}(\d{1,2})\D{1,2}(\d{1,2})/); return m ? Number(m[1]) * 10000 + Number(m[2]) * 100 + Number(m[3]) : null; };
// 按日期从新到旧；没有日期的排在有日期的后面；同样情况保持列表原顺序
const 从新到旧 = 条目们 => 条目们.map((x, i) => ({ x, i, d: 日期值(x.日期) }))
  .sort((a, b) => (a.d == null) - (b.d == null) || (b.d ?? 0) - (a.d ?? 0) || a.i - b.i).map(y => y.x);

// 库里这个比赛已经有的网址：各届次的来源（网址、跳转后网址）和报名网址
function 已有网址(db, 比赛编号) {
  const 有 = new Set();
  for (const 届 of 比赛表.editionsOf(db, 比赛编号)) {
    if (届.registration_url) 有.add(网址键(届.registration_url));
    for (const 源 of db.find('source', { edition_id: 届.id })) {
      if (源.url) 有.add(网址键(源.url));
      if (源.final_url) 有.add(网址键(源.final_url));
    }
  }
  return 有;
}

// 来源表里这个比赛的官方来源（2026-11-08 用户定，取值见 db/描述/表/比赛数据/来源.mjs）：
//   只看 is_official 为真、validity_status 是 valid 的；
//   全部：各届次的官方有效来源 [{ url, source_type, ordinal }]（ordinal 是届次的序号），交给 来源候选 推出起点候选；
//         一条都没有 = 这个比赛一点官方来源都没有（找不到官网时才转待人工审核）；
//   权威名单：authority_notice（如省教育厅公布当年竞赛名单的 PDF），届次从新到旧（同一网址只留一次）；
//   官方通知：届次编号 → 这一届第一条 organizer_notice 的网址（交给挑通知核对用）
function 官方来源(db, 比赛编号) {
  const 届们 = 比赛表.editionsOf(db, 比赛编号);
  const 有效的 = 届们.map(届 => ({ 届, 源们: db.find('source', { edition_id: 届.id }).filter(源 => 源.url && 源.is_official === true && 源.validity_status === 'valid') }));
  const 官方通知 = {};
  for (const { 届, 源们 } of 有效的) {
    const 通知 = 源们.find(源 => 源.source_type === 'organizer_notice');
    if (通知) 官方通知[届.id] = 通知.url;
  }
  const 全部 = 有效的.flatMap(({ 届, 源们 }) => 源们.map(源 => ({ url: 源.url, source_type: 源.source_type, ordinal: 届.ordinal ?? null })));
  const 见过 = new Set();
  const 权威名单 = [...有效的].reverse().flatMap(({ 源们 }) => 源们.filter(源 => 源.source_type === 'authority_notice'))
    .filter(源 => !见过.has(网址键(源.url)) && 见过.add(网址键(源.url)))
    .map(源 => ({ 网址: 源.url, 种类: 源.source_type }));
  return { 全部, 权威名单, 官方通知 };
}

