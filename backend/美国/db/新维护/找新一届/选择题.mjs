// 找新一届 · 给 DeepSeek 的选择题（2026-11-12 用户定）：程序先筛过的搜索结果列出来，让 DeepSeek 挑哪几条是这个比赛新一届的通知或高校转发的通知。
// DeepSeek 只是帮着筛：它选的还要程序读页面再核对比赛名和届次，比赛名对不上的不建。
// 11-12 试验一次交 20 条、上限 4000 token，思考把 token 用完、回答被截断（漏了蓝桥杯）：现在每批最多 10 条，用途 new_edition_pick 的上限调大。
//   选择题(比赛, 目标, 候选) → 文字      候选：[{ title, url, content, date }]；目标：{ 已知年份, 已知届次, 年份, 届次 }
export const 提问版本 = 'new-edition-pick-v1';
export const 每批最多 = 10;
const 摘要最长 = 200;

const 主机 = 网址 => { try { return new URL(网址).hostname; } catch { return ''; } };
const 一条 = (r, i) => {
  const 附 = [主机(r.url), r.date].filter(Boolean).join('，');
  const 摘要 = String(r.content || '').replace(/\s+/g, ' ').trim().slice(0, 摘要最长);
  return [`${i + 1}. ${String(r.title || '（没有标题）').replace(/\s+/g, ' ').trim()}`, `   ${r.url}${附 ? `（${附}）` : ''}`, ...(摘要 ? [`   摘要：${摘要}`] : [])].join('\n');
};

export function 选择题(比赛, 目标, 候选) {
  const 别名 = 比赛.aliases?.length ? `；别名：${比赛.aliases.join('、')}` : '';
  const 主办 = 比赛.organizer ? `；记录里的主办方：${比赛.organizer}` : '';
  const 已知 = [目标.已知年份 ? `${目标.已知年份} 年` : '', 目标.已知届次 || ''].filter(Boolean).join('、') || '不详';
  const 下一 = [目标.年份 ? `${目标.年份} 年` : '', 目标.届次 || ''].filter(Boolean).join('、');
  return [
    `比赛：${比赛.name}${别名}${主办}。库里最新一届是 ${已知}，已经结束。`,
    `下面是搜索这场比赛的 ${候选.length} 条结果。哪几条是这场比赛库里最新一届之后的新一届${下一 ? `（如 ${下一}）` : ''}的举办通知、报名通知，或学校、学院转发的这一届报名通知？`,
    '算：主办方、组委会发布的新一届举办或报名通知；学校、学院转发的新一届全国比赛的报名通知；新一届的官网报名页。',
    '不算：往届的通知；获奖名单、公示、喜报、新闻报道；社团招新；申报承办；学校自己的校赛、校内选拔的实施方案；名字相近的别的比赛；同一系列里的其他赛项或专项赛；聚合站和自媒体的汇总文章。',
    '有的比赛标题按跨年或下一年写（如“2027年第十八届”），以届次为准；没写届次的看年份。',
    '',
    ...候选.map(一条),
    '',
    '最后只回 JSON：{"选":[序号,...],"理由":"一句话"}，可以多选，都不是填 []。',
  ].join('\n');
}
