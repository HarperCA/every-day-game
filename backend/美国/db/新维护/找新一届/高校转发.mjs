// 找高校转发（2026-11-13 用户定）：新维护里官网打不开（读网页、北京代读、无头浏览器都打不开）时，改用第三方通知。
// 复用找新一届那套“学校转发”的搜索和核对（网站.mjs、核对.mjs）：
//   1. 搜（用途 new_edition_search，DeepSeek 搜索）“比赛名 库里最新一届的年份”、“比赛名 今年”（比最新一届晚时）、“比赛名 下一届”（认得出届次时），
//      不带 after:（这一届的转发也要）。
//   2. 程序先筛：只要高校网站（.edu.cn）上、不是已知官方网站（网站.mjs 的 官方主机们）的；屏蔽网站不要；
//      标题是招新、承办、校赛/实施方案、获奖公示报道类的（国家级比赛再加赛区、省赛）排除；标题和摘要里都没有比赛名的排除；
//      标题认得出届次或年份、既不是库里最新一届也不比它新的排除（旧届）。
//   3. 按“标题带年份的在前、日期新的在前”读页面（最多 4 条；标题已认出、这一届已经有了的不读），程序再核对：
//      打得开；页面标题不是排除那类；标题或正文里有比赛名；届次、年份（搜索标题 → 页面标题 → 正文里紧挨着比赛名的）是库里最新一届或比它新。
//   4. 每一届只交一条：库里最新一届的带 届次（编号），新一届的带 新届 { 年份, 届次 }；都带 比赛编号、来源类型 school_repost、核对说明。
//   2026-11-13 服务器试跑抽查出错后用户定的三条（核对.mjs 共用，找新一届 index.mjs 也用）：
//     a. 转发页要够新：发布日期（搜索结果的 date、网址里的日期、正文里的发布时间，取最早的）要在最近 12 个月内；
//        新一届的还要晚于库里最新一届的结束（比赛结束 → 报名截止 → 年份年底）；认不出日期的，只有认出比库里新的届次/年份才用
//        （核对库里最新一届这一届的不比上一届结束，认不出日期的不用）。搜索结果能认出日期的读之前就筛，读到页面再按正文的发布时间核一次。
//     b. 新一届一次最多建一届：同一次找到几个更新的届次，只交最新的（届次/年份最大）；比库里旧或相同的不新建（相同的走核对这一届、只补空）。
//     c. 来源必须是通知详情页：列表页、栏目页、首页（网址像 list*.htm、/list/、index、/col/…）读之前就排除，读到的页面像列表的也不用。
//   不调 DeepSeek 选择题（只用程序核对）；不写库，入库由调用方（维护一个.mjs）交给入库工具（更新已有、不审核；对上已有届次时 06 只补空）。
//   搜索出错照样抛出，由调用方处理（额度类停批，别的当没找到）。
//
//   找高校转发(比赛编号, { db, 会话, 读网页, 屏蔽, 今天 }) → { 条目们, 线索: [{ 网址, 标题, 届次, 年份, 归 }], 过程: [{ 步骤, 说明 }] }
import { 比赛 as 比赛表, 屏蔽网站 } from '../../index.mjs';
import { 名称写法 } from '../找官网/核实.mjs';
import { 认本赛届次, 是新届, 同届, 排除原因, 最新届信息, 届次文字, 有比赛名, 合并认, 同一新届, 发布日期, 上届结束, 太旧原因, 不是详情页原因, 取最新一届 } from './核对.mjs';
import { 主机之, 学校站, 垃圾站, 官方主机们 } from './网站.mjs';

const 来源类型 = 'school_repost';
const 最多读 = 4;
const 读到内容 = new Set(['成功', '正文太短']);
const 净 = s => String(s ?? '').replace(/\s+/g, ' ').trim();
const 日期值 = 日期 => String(日期 || '').slice(0, 10);

export async function 找高校转发(比赛编号, { db, 会话 = null, 读网页, 屏蔽 = [], 今天 } = {}) {
  const 过程 = [];
  const 记 = (步骤, 说明) => 过程.push({ 步骤, 说明 });
  const 线索 = [];
  const 回 = 条目们 => ({ 条目们, 线索, 过程 });
  const 行 = db.get('competition', 比赛编号);
  if (!行) return 回([]);
  const 比赛 = { id: 比赛编号, ...行.data };
  const 届们 = 比赛表.editionsOf(db, 比赛编号);
  const 最新届 = 届们.at(-1);
  if (!最新届) { 记('高校转发', '比赛没有届次，不找'); return 回([]); }
  if (!会话?.search) { 记('高校转发', '没有 AI 会话，不搜'); return 回([]); }
  const 名们 = 名称写法(比赛);
  const 最新 = 最新届信息(届们);
  const 国家级 = 比赛.level === '国家级';
  const 官方们 = 官方主机们(db, 比赛, 届们, 屏蔽);
  const 今年 = Number(String(今天).slice(0, 4));
  const 最新年 = 最新.年止 ?? 最新.年;
  const 结束 = 上届结束(最新届, 最新);
  // 够不够新（2026-11-13）：新一届的要晚于库里最新一届结束、认不出日期要明确更新；都要在最近 12 个月内
  const 太旧 = (日期, 归) => 太旧原因(日期, { 今天, 上届结束: 归 === '新届' ? 结束 : null, 明确更新: 归 === '新届' });

  // 1 搜
  const 后缀们 = [...new Set([最新年 ?? 今年, ...(最新年 != null && 今年 > 最新年 ? [今年] : []), ...(最新.届 != null ? [届次文字(最新.届 + 1, 最新)] : [])].map(String))];
  const 候选 = [];
  const 见过 = new Set();
  for (const 后缀 of 后缀们) {
    const 词 = `${净(比赛.name).slice(0, Math.max(10, 120 - 后缀.length))} ${后缀}`;
    const 结果们 = (await 会话.search({ purpose: 'new_edition_search', query: 词 }))?.references || [];
    const 新的 = 结果们.filter(r => r?.url && !见过.has(r.url) && 见过.add(r.url));
    记('高校转发', `搜「${词}」${结果们.length} 条，新的 ${新的.length} 条`);
    候选.push(...新的);
  }

  // 2 程序先筛
  const 归之 = 认 => (是新届(认, 最新) === true ? '新届' : 同届(认, 最新) ? '这一届' : 认.届 == null && 认.年 == null ? '认不出' : '旧届');
  const 留下 = [];
  const 排掉 = [];
  for (const r of 候选) {
    const 标题 = 净(r.title);
    const h = 主机之(r.url);
    const 不要 = !h ? '网址不对' : 屏蔽网站.isBlockedHost(h, 屏蔽) ? '屏蔽网站' : 垃圾站(h) ? '不是高校网站'
      : 官方们.has(h) ? '已知官方网站（官网打不开）' : !学校站(h) ? '不是高校网站' : 排除原因(标题, { 国家级 }) || 不是详情页原因(r.url, null, { 高校转发: true });
    if (不要) { 排掉.push(`${标题}（${不要}）`); continue; }
    if (!有比赛名(标题, 名们) && !有比赛名(r.content, 名们)) { 排掉.push(`${标题}（没有比赛名）`); continue; }
    const 认 = 认本赛届次(标题, 名们);
    const 归 = 归之(认);
    if (归 === '旧届') { 排掉.push(`${标题}（旧届）`); continue; }
    // 搜索结果、网址里认得出日期的，读之前先看够不够新（认不出届次的先只看 12 个月，读到页面再全核）
    const 日 = 发布日期({ 搜索日期: r.date, 网址: r.url });
    const 旧 = 日 ? 太旧(日, 归) : '';
    if (旧) { 排掉.push(`${标题}（${旧}）`); continue; }
    留下.push({ ...r, 标题, 认, 归 });
  }
  记('高校转发', `候选 ${候选.length} 条，留 ${留下.length} 条${排掉.length ? `；排除：${排掉.join('；')}` : ''}`);

  // 3 读、核对；每一届只要一条
  const 排序 = [...留下].sort((a, b) => (a.认.年 == null) - (b.认.年 == null) || 日期值(b.date).localeCompare(日期值(a.date)));
  let 这一届 = null;
  const 新届组们 = [];
  const 已有 = (归, 认) => (归 === '这一届' ? Boolean(这一届) : 归 === '新届' ? 新届组们.some(g => 同一新届(g, 认)) : false);
  let 读了 = 0;
  for (const r of 排序) {
    if (读了 >= 最多读) break;
    if (已有(r.归, r.认)) { 记('高校转发', `${r.url}：同一届已有，不读`); continue; }
    读了 += 1;
    let 页;
    try { 页 = (await 读网页(r.url)) || { status: '出错', error: '读网页没有交回结果' }; } catch (error) { 页 = { status: '网络错误', error: String(error?.message || error).slice(0, 200) }; }
    if (!读到内容.has(页?.status)) { 记('高校转发', `${r.url}：打不开（${页?.error || 页?.status || '没有返回'}）`); continue; }
    const 题 = 净(页.title);
    const 排 = 排除原因(题, { 国家级 });
    if (排) { 记('高校转发', `${r.url}：页面标题是${排}`); continue; }
    const 非详情 = 不是详情页原因(页.finalUrl || r.url, 页, { 高校转发: true });
    if (非详情) { 记('高校转发', `${r.url}：${非详情}，不用`); continue; }
    if (!有比赛名(`${题} ${页.text || ''}`, 名们)) { 记('高校转发', `${r.url}：页面上没有比赛名`); continue; }
    const 正文认 = 认本赛届次(String(页.text || '').slice(0, 20000), 名们, { 兜底: false });
    const 页认 = 合并认(认本赛届次(题, 名们), 正文认);
    const 认 = 合并认(页认, r.认);
    if (归之(认) === '新届' && 归之(页认) !== '新届') {
      记('高校转发', `${r.url}：通知详情未证实是新一届，不用`);
      continue;
    }
    const 归 = 归之(认);
    if (归 !== '这一届' && 归 !== '新届') { 记('高校转发', `${r.url}：${归 === '旧届' ? '旧届' : '认不出届次年份'}，不用`); continue; }
    if (已有(归, 认)) { 记('高校转发', `${r.url}：同一届已有，不用`); continue; }
    const 旧 = 太旧(发布日期({ 搜索日期: r.date, 网址: [r.url, 页.finalUrl].filter(Boolean), 正文: 页.text }), 归);
    if (旧) { 记('高校转发', `${r.url}：${旧}，不用`); continue; }
    const 届次 = 认.届 != null ? 届次文字(认.届, 最新) : null;
    const 年份 = 认.年 == null ? null : 认.年止 && 认.年止 !== 认.年 ? `${认.年}—${认.年止}` : String(认.年);
    线索.push({ 网址: r.url, 标题: r.标题, 届次, 年份, 归 });
    记('高校转发', `${r.url}：对上了（${归}${[年份 && `，${年份}年`, 届次 && `，${届次}`].filter(Boolean).join('')}）`);
    const 条 = { 网址: r.url, 标题: r.标题, 比赛名: 比赛.name, 比赛编号, 来源类型 };
    if (归 === '这一届') {
      这一届 = { ...条, 届次: 最新届.id,
        核对说明: `新维护 ${今天}：官网打不开，用高校转发（${主机之(r.url)}）核对库里最新一届，不算官方来源，只补空；程序核对过比赛名和届次（2026-11-13 用户定）` };
    } else {
      新届组们.push({ 届: 认.届, 年: 认.年, 条: { ...条, 新届: { 年份, 届次 },
        核对说明: `新维护 ${今天}：官网打不开，用高校转发（${主机之(r.url)}）发现新一届，不算官方来源；程序核对过比赛名和届次（2026-11-13 用户定）` } });
    }
  }
  // 新一届一次最多建一届：只交最新的那一届（2026-11-13 用户定）
  const 最新组 = 取最新一届(新届组们);
  const 届名 = g => (g.届 != null ? 届次文字(g.届, 最新) : `${g.年}年`);
  if (新届组们.length > 1) 记('高校转发', `同时找到 ${新届组们.map(届名).join('、')}，只建最新的${届名(最新组)}（一次最多一届）`);
  const 条目们 = [...(这一届 ? [这一届] : []), ...(最新组 ? [最新组.条] : [])];
  记('高校转发', 条目们.length ? `交给入库 ${条目们.length} 条` : '没找到这一届或新一届的高校转发');
  return 回(条目们);
}
