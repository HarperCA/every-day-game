// 找官网 · 搜索记忆的改动：成功时写域名、DeepSeek 用过的搜索词（年份、届次留空，注明哪家搜的）、通知标题格式；失败时写一条教训（最多 3 条，挤掉最旧的）。
// 只交回变了的节，每节是完整的新列表；写进比赛库用 写回记忆（经 db/index.mjs 的 搜索记忆.改节）。
//   模板化(文字, 目标) → 年份换成 {年份}、届次换成 {届次}（目标的和库里最新一届的都换）
//   成功改动(节, { 域名, 搜索词们, 搜索, 标题 }, 目标) → { 官方域名?, 成功过的搜索词?, 往年通知标题格式? }
//   教训改动(节, 一条) → { 教训 }
//   维护记录改动(节, 一行) → { 维护记录 }   2026-11-08 用户定：每次维护（成功失败都）记一行，最新在前，只留最近 5 条；
//                                          一行如“2026-11-08 成功：没有变化（指纹和上次一样，跳过）”，太长的写入时截到 200 字
//   写回记忆(db, 比赛编号, 改动, { 操作人 }) → { id, version } 或 null（没有改动）
import { 搜索记忆 } from '../../index.mjs';

const 每节最多 = 5;
const 通知标题 = /^关于.{2,80}(通知|公告)$/;

export function 模板化(文字, { 年份, 届次, 已知年份 = null, 已知届次 = null } = {}) {
  let 结果 = String(文字);
  for (const 届 of [届次, 已知届次]) if (届) 结果 = 结果.replaceAll(届, '{届次}');
  for (const 年 of [年份, 已知年份]) if (年 != null) 结果 = 结果.replaceAll(String(年), '{年份}');
  return 结果;
}

// 条目开头的域名（后面可能跟着“（比赛库官网字段，还没核实）”这类说明）
const 条目域名 = 条目 => String(条目).split(/[（(\s]/)[0].toLowerCase().replace(/^https?:\/\//, '').replace(/^www\./, '').replace(/\/.*$/, '');
const 一样 = (a, b) => JSON.stringify(a) === JSON.stringify(b);

export function 成功改动(节, { 域名, 搜索词们 = [], 搜索, 标题 }, 目标) {
  const 改动 = {};
  const 旧域名 = 节?.官方域名 || [];
  const 新域名 = [域名, ...旧域名.filter(条 => 条目域名(条) !== 域名)];
  if (!一样(新域名, 旧域名)) 改动.官方域名 = 新域名;
  const 旧词 = 节?.成功过的搜索词 || [];
  const 新词 = [...new Set(搜索词们.map(词 => `${模板化(String(词).replace(/\s+/g, ' ').trim(), 目标)}（${搜索}）`))].filter(条 => !旧词.includes(条));
  if (新词.length) 改动.成功过的搜索词 = [...新词, ...旧词].slice(0, 每节最多);
  const 干净标题 = String(标题 || '').trim();
  if (通知标题.test(干净标题)) {
    const 格式 = 模板化(干净标题, 目标);
    const 旧 = 节?.往年通知标题格式 || [];
    if (!旧.includes(格式)) 改动.往年通知标题格式 = [格式, ...旧].slice(0, 每节最多);
  }
  return 改动;
}

export function 教训改动(节, 一条) {
  return { 教训: [...(节?.教训 || []), 一条].slice(-搜索记忆.最多教训) };
}

// 节可以是 null（还没有记忆）或旧记忆（没有维护记录这一节）
export function 维护记录改动(节, 一行) {
  return { 维护记录: [一行, ...(节?.维护记录 || [])].slice(0, 搜索记忆.最多维护记录) };
}

export function 写回记忆(db, 比赛编号, 改动, { 操作人 = '找官网' } = {}) {
  if (!改动 || !Object.keys(改动).length) return null;
  const 现在 = 搜索记忆.读(db, 比赛编号);
  return 搜索记忆.改节(db, 比赛编号, 改动, { 版本: 现在?.version ?? null, 操作人 });
}
