// 新维护 · 挑通知：从这次要考虑的通知列表条目里，挑出交给入库工具的几条（纯函数，不读库、不读网页）。
//
// 2026-11-08 用户定：一届只用一条主通知核对。起因：湖南省大学生数学竞赛同一次维护里，“2025年第九届获奖名单公示”
// 和“2025年第九届举办通知”两条都被拿去核对 2025 那一届，先被获奖公示改坏 7 处、又被举办通知改回去。
//
// 规则：
//   1. 标题里没有比赛名的排除；标题含获奖、名单、公示、复赛等（非主通知关键词）的排除——这类通知不拿来改字段。
//      其余（关于举办/开展/组织……的通知、报名通知、竞赛通知、延期通知等）算主通知。
//   2. 从标题认年份（20xx，“2025—2026”取前一个）和届次（第九届、第9届），和库里届次的 edition_year / edition_ordinal 对；
//      任一对上就算这一届，两者冲突时以届次为准。
//   3. 已有届次：这次的条目里有指向这一届的主通知时才核对——存了官方通知的用存的那条核对，列表里同届的主通知排除；
//      没存的取同届最新一条（按日期新到旧，没日期的按列表原顺序排在后面）。
//      （审查 11-08：以前最新一届存了官方通知就每次都核对，列表一有无关变动就重跑旧通知，读全文也走不到；
//        现在最新一届也只在有指向它的主通知、或有认不出届次的主通知（当作最新一届）时才用存的核对。）
//   4. 比库里最新一届新的：每个新届取最新一条。
//   5. 认不出年份、届次的：当作指向最新一届。最新一届存了官方通知 → 用存的核对，认不出的都排除；
//      没存、也没有对上最新一届的通知 → 取最新一条当作最新一届核对；否则排除。
//   6. 核对加新届最多 `最多` 条，优先级：新届（越新越前）→ 最新一届 → 较旧届次（越新越前），超出的排除。
//   7. 库里没有届次：所有主通知当新届（每个年份/届次一条，认不出的另取最新一条）。
//
// 挑通知({ 条目们, 届次们, 官方通知, 有比赛名, 最多 = 3 })
//   → { 核对: [{ 网址, 标题, 届次 }], 新届: [{ 网址, 标题 }], 排除: [{ 标题, 网址, 原因 }], 说明: [文字] }

// 标题里有这些词的不是主通知（获奖/公示/复赛这类），不拿来核对字段
export const 非主通知关键词 = ['获奖', '名单', '公示', '结果', '成绩', '复赛', '决赛', '颁奖', '表彰', '拟推荐', '晋级', '入围', '证书'];

// 排除的原因（说明里按简称计数）
export const 排除原因 = {
  没有比赛名: '标题里没有比赛名',
  非主通知: '获奖/公示类通知，不拿来核对',
  用存的: '这一届用库里存的官方通知核对',
  同届: '同一届只用一条主通知',
  认不出: '认不出是哪一届',
  旧届没有: '比库里最新一届旧，库里没有这一届',
  超上限: '超过每次上限',
};
const 简称 = {
  [排除原因.没有比赛名]: '没有比赛名',
  [排除原因.非主通知]: '获奖/公示类',
  [排除原因.用存的]: '用库里存的官方通知',
  [排除原因.同届]: '同一届只用一条',
  [排除原因.认不出]: '认不出届次',
  [排除原因.旧届没有]: '库里没有这一届',
  [排除原因.超上限]: '超过每次上限',
};
const 存的标题 = '（库里存的官方通知）';

const 中文数 = { 零: 0, 〇: 0, 一: 1, 二: 2, 两: 2, 三: 3, 四: 4, 五: 5, 六: 6, 七: 7, 八: 8, 九: 9 };
const 中文位 = { 十: 10, 百: 100, 千: 1000 };
function 中文转数(文字) {
  if (/^\d+$/.test(文字)) return Number(文字);
  let 合计 = 0, 当前 = 0;
  for (const 字 of 文字) {
    if (字 in 中文数) 当前 = 中文数[字];
    else if (字 in 中文位) { 合计 += (当前 || 1) * 中文位[字]; 当前 = 0; }
    else return null;
  }
  return 合计 + 当前 || null;
}

// 认年份('关于举办2026年第十届……') → 2026；“2025—2026”取前一个；认不出给 null
export function 认年份(文字) {
  const m = String(文字 ?? '').match(/(?<!\d)((?:19|20)\d{2})(?!\d)/);
  return m ? Number(m[1]) : null;
}

// 认届次('第九届') → 9；中文数字、阿拉伯数字都认；认不出给 null
export function 认届次(文字) {
  const m = String(文字 ?? '').match(/第\s*(\d+|[零〇一二两三四五六七八九十百千]+)\s*届/);
  return m ? 中文转数(m[1]) : null;
}
const 届次原文 = 文字 => String(文字 ?? '').match(/第\s*(?:\d+|[零〇一二两三四五六七八九十百千]+)\s*届/)?.[0].replace(/\s+/g, '') ?? null;

const 去www = 域名 => String(域名 || '').toLowerCase().replace(/^www\./, '');
const 网址键 = 网址 => { try { const u = new URL(网址); return `${去www(u.hostname)}${u.pathname.replace(/\/+$/, '')}${u.search}`; } catch { return String(网址 || '').trim(); } };
// 条目日期变成可比的数（2026-10-01、2026/10/1、2026.10.1、2026年10月1日都认）；没有日期给 null
const 日期值 = 日期 => { const m = String(日期 || '').match(/((?:19|20)\d{2})\D{1,2}(\d{1,2})\D{1,2}(\d{1,2})/); return m ? Number(m[1]) * 10000 + Number(m[2]) * 100 + Number(m[3]) : null; };
// 按日期从新到旧；没有日期的排在有日期的后面；同样情况保持列表原顺序（条目带 序 = 列表里的位置）
const 从新到旧 = 们 => [...们].sort((a, b) => (a.日 == null) - (b.日 == null) || (b.日 ?? 0) - (a.日 ?? 0) || a.序 - b.序);
const 届标签 = 届 => 届.edition_ordinal || (届.edition_year ? `${届.edition_year}年` : '') || 届.edition_name || 届.id;
const 新届标签 = ({ 年, 届文 }) => `${年 ? `${年}年` : ''}${届文 || ''}` || '认不出届次';

export function 挑通知({ 条目们 = [], 届次们 = [], 官方通知 = {}, 有比赛名, 最多 = 3 } = {}) {
  官方通知 = 官方通知 || {};
  const 排除 = [];
  const 排 = (x, 原因) => 排除.push({ 标题: x.标题, 网址: x.网址, 原因 });

  // 1 去重（同一链接只算一次）、筛主通知
  const 主通知们 = [];
  const 见过 = new Set();
  (条目们 || []).forEach((条目, 序) => {
    const x = { 标题: String(条目.标题 ?? '').trim(), 网址: 条目.链接, 日: 日期值(条目.日期), 序 };
    const 键 = 网址键(x.网址);
    if (见过.has(键)) return;
    见过.add(键);
    if (!有比赛名(x.标题)) return 排(x, 排除原因.没有比赛名);
    if (非主通知关键词.some(词 => x.标题.includes(词))) return 排(x, 排除原因.非主通知);
    x.年 = 认年份(x.标题);
    x.届 = 认届次(x.标题);
    x.届文 = 届次原文(x.标题);
    主通知们.push(x);
  });

  // 2 认届次：对上已有届次 / 新届 / 库里没有的旧届 / 认不出
  // edition_year / edition_ordinal 没写时从届次全称（edition_name，如“2025 年数学建模”）里认
  const 届们 = (届次们 || []).map(届 => ({ 届, 年: 认年份(届.edition_year) ?? 认年份(届.edition_name), 序号: 认届次(届.edition_ordinal) ?? 认届次(届.edition_name) }));
  const 最新 = 届们.at(-1)?.届 ?? null;
  const 最大届 = Math.max(...届们.map(y => y.序号 ?? -Infinity));
  const 最大年 = Math.max(...届们.map(y => y.年 ?? -Infinity));
  const 有届序 = Number.isFinite(最大届), 有年 = Number.isFinite(最大年);
  const 找最后 = 条件 => [...届们].reverse().find(条件)?.届 ?? null;
  function 归属(x) {
    if (x.届 == null && x.年 == null) return { 种类: '认不出' };
    if (!届们.length) return { 种类: '新' };
    if (x.届 != null) {
      const 对上 = 找最后(y => y.序号 === x.届);
      if (对上) return { 种类: '已有', 届: 对上 };
      // 届次没对上：年份只和没写届次的届比（写了届次的一定冲突，以届次为准）
      const 年对上 = x.年 != null && 找最后(y => y.序号 == null && y.年 === x.年);
      if (年对上) return { 种类: '已有', 届: 年对上 };
      if (有届序) return x.届 > 最大届 ? { 种类: '新' } : { 种类: '旧届没有' };
    }
    if (x.年 == null || !有年) return { 种类: '认不出' };
    const 年对上 = 找最后(y => y.年 === x.年);
    if (年对上) return { 种类: '已有', 届: 年对上 };
    return x.年 > 最大年 ? { 种类: '新' } : { 种类: '旧届没有' };
  }

  const 已有组 = new Map();   // 届次编号 → 主通知们
  const 新组们 = [];          // [{ 年, 届, 届文, 们 }]
  const 认不出们 = [];
  for (const x of 主通知们) {
    const 归 = 归属(x);
    if (归.种类 === '已有') { if (!已有组.has(归.届.id)) 已有组.set(归.届.id, []); 已有组.get(归.届.id).push(x); }
    else if (归.种类 === '新') {
      // 同一新届：届次相同，或届次不冲突而年份相同
      const 组 = 新组们.find(g => (x.届 != null && g.届 === x.届) || ((x.届 == null || g.届 == null) && x.年 != null && g.年 === x.年));
      if (组) { 组.们.push(x); 组.年 ??= x.年; 组.届 ??= x.届; 组.届文 ??= x.届文; }
      else 新组们.push({ 年: x.年, 届: x.届, 届文: x.届文, 们: [x] });
    } else if (归.种类 === '旧届没有') 排(x, 排除原因.旧届没有);
    else 认不出们.push(x);
  }

  // 3 候选（按优先级排好）：新届 → 最新一届 → 较旧届次
  const 候选 = [];   // { 类: '新届'|'核对', 网址, 标题, 届次?, 说明 }
  // 新届：越新越前（都有届次比届次，都有年份比年份，否则比最新那条的日期）
  const 组最新 = g => 从新到旧(g.们)[0];
  新组们.sort((a, b) => (a.届 != null && b.届 != null ? b.届 - a.届 : a.年 != null && b.年 != null ? b.年 - a.年 : (组最新(b).日 ?? 0) - (组最新(a).日 ?? 0)));
  for (const g of 新组们) {
    const [选, ...其余] = 从新到旧(g.们);
    候选.push({ 类: '新届', 网址: 选.网址, 标题: 选.标题, 说明: `新届（${新届标签(g)}）：${选.标题}` });
    其余.forEach(x => 排(x, 排除原因.同届));
  }
  // 没有届次：认不出的取最新一条也当新届
  if (!届们.length && 认不出们.length) {
    const [选, ...其余] = 从新到旧(认不出们);
    候选.push({ 类: '新届', 网址: 选.网址, 标题: 选.标题, 说明: `新届（认不出届次）：${选.标题}` });
    其余.forEach(x => 排(x, 排除原因.认不出));
  }
  // 已有届次：最新一届在前，较旧的越新越前
  // 有指向 届 的主通知（们 非空，或 有认不出的 当作指向最新一届）才核对
  const 核对一届 = (届, 们, 有认不出 = false) => {
    const 存的 = 官方通知[届.id];
    if (存的) {
      const 键 = 网址键(存的);
      const 同网址 = 们.find(x => 网址键(x.网址) === 键);
      们.filter(x => x !== 同网址).forEach(x => 排(x, 排除原因.用存的));
      if (们.length || 有认不出) 候选.push({ 类: '核对', 网址: 存的, 标题: 同网址?.标题 || 存的标题, 届次: 届.id, 说明: `核对${届标签(届)}：用库里存的官方通知` });
      return;
    }
    if (!们.length) return;
    const [选, ...其余] = 从新到旧(们);
    候选.push({ 类: '核对', 网址: 选.网址, 标题: 选.标题, 届次: 届.id, 说明: `核对${届标签(届)}：${选.标题}` });
    其余.forEach(x => 排(x, 排除原因.同届));
  };
  if (最新) {
    const 们 = 已有组.get(最新.id) || [];
    核对一届(最新, 们, 认不出们.length > 0);
    // 认不出的：最新一届没存官方通知、也没有对上它的通知时，取最新一条当作最新一届核对
    if (认不出们.length) {
      const 顺 = 从新到旧(认不出们);
      if (!官方通知[最新.id] && !们.length) {
        const 选 = 顺.shift();
        候选.push({ 类: '核对', 网址: 选.网址, 标题: 选.标题, 届次: 最新.id, 说明: `核对${届标签(最新)}（认不出届次，当作最新一届）：${选.标题}` });
      }
      顺.forEach(x => 排(x, 排除原因.认不出));
    }
    for (const 届 of [...届次们].reverse().slice(1)) 核对一届(届, 已有组.get(届.id) || []);
  }

  // 4 上限
  const 选中 = 候选.slice(0, Math.max(0, 最多));
  候选.slice(选中.length).forEach(x => 排(x, 排除原因.超上限));
  const 核对 = 选中.filter(x => x.类 === '核对').map(({ 网址, 标题, 届次 }) => ({ 网址, 标题, 届次 }));
  const 新届 = 选中.filter(x => x.类 === '新届').map(({ 网址, 标题 }) => ({ 网址, 标题 }));

  // 5 说明
  const 说明 = 选中.map(x => x.说明);
  if (!选中.length) 说明.push('没有可用的通知');
  if (排除.length) {
    const 计 = new Map();
    for (const x of 排除) 计.set(简称[x.原因] || x.原因, (计.get(简称[x.原因] || x.原因) || 0) + 1);
    说明.push(`排除 ${排除.length} 条（${[...计].map(([名, 数]) => `${名} ${数}`).join('，')}）`);
  }
  return { 核对, 新届, 排除, 说明 };
}
