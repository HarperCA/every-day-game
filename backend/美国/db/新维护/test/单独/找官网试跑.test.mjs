// 试跑命令里算目标：要找哪一年、第几届（2026-11-07）
import { expect, test } from 'vitest';
import { 下一届, 算目标 } from '../../找官网/试跑.mjs';

test('下一届：中文数字和阿拉伯数字都能加一', () => {
  expect(下一届('第十七届')).toBe('第十八届');
  expect(下一届('第九届')).toBe('第十届');
  expect(下一届('第十九届')).toBe('第二十届');
  expect(下一届('第二十届')).toBe('第二十一届');
  expect(下一届('第9届')).toBe('第10届');
  expect(下一届('2025年')).toBeNull();
  expect(下一届(null)).toBeNull();
});

const 届 = (ordinal, edition_year, edition_ordinal) => ({ ordinal, edition_year, edition_ordinal });

test('最新一届早于今年：找今年，届次不猜', () => {
  expect(算目标([届(1, '2024', '第七届'), 届(2, '2025', '第八届')], '2026-11-07')).toEqual({ 年份: 2026, 届次: null, 已知年份: 2025, 已知届次: '第八届' });
});
test('最新一届就是今年或更晚：找下一年、下一届', () => {
  expect(算目标([届(1, '2025', '第八届'), 届(2, '2026', '第九届')], '2026-11-07')).toEqual({ 年份: 2027, 届次: '第十届', 已知年份: 2026, 已知届次: '第九届' });
  expect(算目标([届(1, '2025—2026', null)], '2025-11-07')).toEqual({ 年份: 2026, 届次: null, 已知年份: 2025, 已知届次: null });
});
test('没有届次、年份认不出：找今年', () => {
  expect(算目标([], '2026-11-07')).toEqual({ 年份: 2026, 届次: null, 已知年份: null, 已知届次: null });
  expect(算目标([届(1, null, '第三届')], '2026-11-07')).toEqual({ 年份: 2026, 届次: null, 已知年份: null, 已知届次: '第三届' });
});
test('命令行给了就用给的', () => {
  expect(算目标([届(1, '2026', '第九届')], '2026-11-07', { 年份: '2026', 届次: '第九届' })).toEqual({ 年份: 2026, 届次: '第九届', 已知年份: 2026, 已知届次: '第九届' });
});
