// 新维护 · 挑通知（2026-11-08 用户定：一届只用一条主通知核对）
//   已有届次重读它自己存着的官方通知；没存的从列表里找年份、届次对得上的“关于举办……”那条；
//   获奖名单、公示、复赛这类通知不拿来改字段。新的一届每届一条；核对加新届最多 3 条（新届 → 最新一届 → 较旧届次）。
import { describe, expect, test } from 'vitest';
import { 挑通知, 非主通知关键词, 认年份, 认届次 } from '../../挑通知.mjs';

const 湖南名 = '湖南省大学生数学竞赛';
const 有湖南名 = 标题 => String(标题).includes(湖南名);
const 站 = 'https://math.hnu.edu.cn/info/';
const 条 = (标题, 号, 日期) => ({ 标题, 链接: `${站}${号}.htm`, 日期 });

// 湖南数学竞赛那组真实标题
const 十届通知 = 条('关于举办2026年第十届湖南省大学生数学竞赛的通知', 110, '2026-10-20');
const 九届获奖 = 条('关于2025年第九届湖南省大学生数学竞赛获奖名单公示的通知(公示结束)', 101, '2025-12-15');
const 九届通知 = 条('关于举办2025年第九届湖南省大学生数学竞赛的通知', 100, '2025-10-10');
const 全国初赛 = 条('关于举办第十八届全国大学生数学竞赛初赛（湖南赛区）的通知', 105, '2026-09-01');
const 湖南条目 = [十届通知, 九届获奖, 九届通知, 全国初赛];
const 湖南届次 = [
  { id: 'ed-8', edition_year: '2024', edition_ordinal: '第八届', edition_name: '2024年第八届湖南省大学生数学竞赛' },
  { id: 'ed-9', edition_year: '2025', edition_ordinal: '第九届', edition_name: '2025年第九届湖南省大学生数学竞赛' },
];
const 原因表 = 结果 => Object.fromEntries(结果.排除.map(x => [x.标题, x.原因]));

describe('湖南省大学生数学竞赛（本地实测出问题的那组）', () => {
  test('第九届存了官方通知：新届 = 2026 第十届；核对 = 存的官方通知；获奖公示、同届举办通知、不带本赛名的都排除', () => {
    const 存的 = `${站}九届存档.htm`;
    const 结果 = 挑通知({ 条目们: 湖南条目, 届次们: 湖南届次, 官方通知: { 'ed-9': 存的 }, 有比赛名: 有湖南名 });
    expect(结果.新届).toEqual([{ 网址: 十届通知.链接, 标题: 十届通知.标题 }]);
    expect(结果.核对).toEqual([{ 网址: 存的, 标题: '（库里存的官方通知）', 届次: 'ed-9' }]);
    const 原因 = 原因表(结果);
    expect(原因[九届获奖.标题]).toMatch(/获奖\/公示类/);
    expect(原因[九届通知.标题]).toMatch(/库里存的官方通知/);
    expect(原因[全国初赛.标题]).toMatch(/标题里没有比赛名/);
    expect(结果.排除).toHaveLength(3);
    expect(结果.排除.every(x => x.网址 && x.标题 && x.原因)).toBe(true);
    const 说明 = 结果.说明.join('\n');
    expect(说明).toContain('核对第九届：用库里存的官方通知');
    expect(说明).toContain('新届');
    expect(说明).toContain('第十届');
    expect(说明).toMatch(/排除 3 条/);
  });

  test('存的官方通知就在列表里：标题用列表里的，这一条不算排除', () => {
    const 结果 = 挑通知({ 条目们: 湖南条目, 届次们: 湖南届次, 官方通知: { 'ed-9': 九届通知.链接 }, 有比赛名: 有湖南名 });
    expect(结果.核对).toEqual([{ 网址: 九届通知.链接, 标题: 九届通知.标题, 届次: 'ed-9' }]);
    expect(结果.排除.map(x => x.标题)).not.toContain(九届通知.标题);
  });

  test('第九届没存官方通知：核对 = “关于举办2025年第九届……”那条，获奖公示排除', () => {
    const 结果 = 挑通知({ 条目们: 湖南条目, 届次们: 湖南届次, 官方通知: {}, 有比赛名: 有湖南名 });
    expect(结果.新届).toEqual([{ 网址: 十届通知.链接, 标题: 十届通知.标题 }]);
    expect(结果.核对).toEqual([{ 网址: 九届通知.链接, 标题: 九届通知.标题, 届次: 'ed-9' }]);
    const 原因 = 原因表(结果);
    expect(原因[九届获奖.标题]).toMatch(/获奖\/公示类/);
    expect(原因[全国初赛.标题]).toMatch(/标题里没有比赛名/);
    expect(结果.排除).toHaveLength(2);
    expect(结果.说明.join('\n')).toContain('核对第九届：关于举办2025年第九届湖南省大学生数学竞赛的通知');
  });

  // 审查 11-08：以前最新一届存了官方通知就每次都交回一条核对，列表一有无关变动就重跑旧通知
  test('最新一届存了官方通知，但这次的条目里没有指向它的主通知（只有新届、别的届、获奖公示、不带比赛名的）：不用存的核对', () => {
    const 存的 = `${站}九届存档.htm`;
    const 只新届 = 挑通知({ 条目们: [十届通知, 全国初赛], 届次们: 湖南届次, 官方通知: { 'ed-9': 存的 }, 有比赛名: 有湖南名 });
    expect(只新届.核对).toEqual([]);
    expect(只新届.新届).toEqual([{ 网址: 十届通知.链接, 标题: 十届通知.标题 }]);
    const 只获奖 = 挑通知({ 条目们: [九届获奖, 全国初赛], 届次们: 湖南届次, 官方通知: { 'ed-9': 存的 }, 有比赛名: 有湖南名 });
    expect(只获奖).toMatchObject({ 核对: [], 新届: [] });
    const 只旧届 = 挑通知({ 条目们: [条('关于举办2024年第八届湖南省大学生数学竞赛的通知', 80, '2024-10-01')], 届次们: 湖南届次, 官方通知: { 'ed-9': 存的 }, 有比赛名: 有湖南名 });
    expect(只旧届.核对).toEqual([{ 网址: `${站}80.htm`, 标题: '关于举办2024年第八届湖南省大学生数学竞赛的通知', 届次: 'ed-8' }]);
    const 空 = 挑通知({ 条目们: [], 届次们: 湖南届次, 官方通知: { 'ed-9': 存的 }, 有比赛名: 有湖南名 });
    expect(空.核对).toEqual([]);
  });

  test('官方通知没给（undefined）也能用', () => {
    const 结果 = 挑通知({ 条目们: 湖南条目, 届次们: 湖南届次, 有比赛名: 有湖南名 });
    expect(结果.核对.map(x => x.网址)).toEqual([九届通知.链接]);
  });
});

