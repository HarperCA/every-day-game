    const 条目们 = [
      条('关于举办2026年第十届大赛的通知', 1, '2026-03-01'),
      条('第十届大赛补充通知', 2, '2026-04-01'),
      条('关于举办2025年第九届大赛的通知', 3, '2025-03-01'),
      条('大赛报名通知', 4, '2026-05-01'),
      条('大赛考场通知', 5, '2026-01-01'),
      条('第九届大赛获奖名单', 6, '2025-12-01'),
    ];
    const 结果 = 挑通知({ 条目们, 届次们: [], 官方通知: {}, 有比赛名: 有名 });
