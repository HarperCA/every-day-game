// 建库 · 报告：把计划和写入结果写成给人看的 Markdown：写了多少、怎么合并的、每个问题怎么处理的。
export function 写报告({ 来源文件, 导出时间, 旧条数, 计划, 写入结果, 核对结果 }) {
  const 行 = [];
  const 表 = (头, 行们) => [`| ${头.join(' | ')} |`, `|${头.map(() => '---').join('|')}|`, ...行们.map(r => `| ${r.map(v => String(v ?? '').replace(/\|/g, '／').replace(/\n/g, ' ')).join(' | ')} |`)];
  行.push('# 建库报告', '', `- 旧数据：${来源文件}（导出时间 ${导出时间}，${旧条数} 条）`,
    `- 写进比赛库：比赛 ${写入结果.比赛}、届次 ${写入结果.届次}、来源 ${写入结果.来源}、处理记录 ${写入结果.处理记录}`,
    `- 没搬的届次：${旧条数 - 写入结果.届次} 条（原因见“问题”）`,
    ...(核对结果 ? [`- 核对：旧记录里有值的字段一共 ${核对结果.检查了} 个，在新库里对得上 ${核对结果.对得上} 个；比赛级字段取了代表那届、其余届次不同的 ${核对结果.比赛级取代表那届} 个；**找不到 ${核对结果.找不到.length} 个**`] : []), '');
  if (核对结果?.找不到.length) 行.push('### 核对时找不到的', '', ...表(['届次', '旧字段', '原值'], 核对结果.找不到.map(x => [x.届次, x.字段, x.原值])), '');

  行.push('## 拆成独立比赛的（借用了上级比赛的编号）', '', 计划.拆开们.length ? `共 ${计划.拆开们.length} 条：旧数据里它们的 eventId 和上级比赛相同，拆成各自独立的比赛，上级比赛指向原编号。` : '没有。', '');
  if (计划.拆开们.length) 行.push(...表(['届次编号', '名称', '新比赛编号', '上级比赛'], 计划.拆开们.map(x => [x.届次, x.名称, x.新编号, x.上级])), '');

  const 重复 = 计划.合并组们.filter(g => g.同一届重复?.length);
  行.push('## 同一届出现两条的（要人定留哪条）', '', 重复.length ? `共 ${重复.length} 个比赛。现在两条都搬进来了（届次顺序不同），定了以后把不要的那条改成下架或归档。` : '没有。', '');
  for (const g of 重复) 行.push(`- ${g.名称}（${g.编号}）：第 ${g.同一届重复.join('、')} 届重复 —— ${g.届次们.map(e => `${e.id}（${e.状态}）`).join('、')}`);
  if (重复.length) 行.push('');

  const 同名合并 = 计划.合并组们.filter(g => g.旧eventId们.length > 1);
  行.push('## 合并成同一个比赛的', '', `共 ${计划.合并组们.length} 组。其中 ${同名合并.length} 组是不同 eventId 因为名称相同合并的，**要人看一下是不是真的同一个比赛**。`, '');
  for (const g of 计划.合并组们) {
    行.push(`### ${g.名称}（${g.编号}）${g.旧eventId们.length > 1 ? ' — 名称相同合并，要人看' : ''}`, '');
    行.push(...表(['顺序', '届次编号', '年份', '第几届', '状态', '届次全称', '为什么合进来'], g.届次们.map((e, i) => [i + 1, e.id, e.年份, e.第几届, e.状态, e.届次名, e.理由 || '（这一组的第一条）'])));
    if (g.级别不同) 行.push('', `- 各届级别不同：${g.级别不同.join(' / ')}（比赛用代表那届的，其余届次自己记）`);
    if (g.主办方不同) 行.push('', `- 各届主办方不同：${g.主办方不同.join(' / ')}`);
    行.push('');
  }

  const 改号 = Object.entries(计划.编号对照).filter(([旧, 新]) => 旧 !== 新);
  行.push('## 编号对照（被合并掉的 eventId）', '', 改号.length ? '' : '没有。');
  if (改号.length) 行.push(...表(['旧 eventId', '新比赛编号'], 改号), '');

  行.push('## 问题和处理', '');
  if (!计划.问题们.length) 行.push('没有。');
  else {
    const 按类 = new Map();
    for (const p of 计划.问题们) { const k = `${p.字段}：${p.处理.replace(/：.*$/, '')}`; 按类.set(k, (按类.get(k) || 0) + 1); }
    行.push('按类汇总：', '', ...表(['字段：处理', '条数'], [...按类].sort((a, b) => b[1] - a[1])), '', '明细：', '');
    行.push(...表(['届次或比赛', '字段', '处理', '原值'], 计划.问题们.map(p => [p.届次, p.字段, p.处理, p.原值 ?? ''])));
  }
  return 行.join('\n') + '\n';
}
