// 呈现调度：首页列表的总流程，只管按顺序调三步，自己不做判断。
//   呈现首页(请求, { 主库, 副库, 用户id, now, 海报地址, 海报目录 })
//     1. 用户输入/  整理输入(请求)            小程序带来的请求 → 统一的条件
//     2. 排序规则/  排序(条件, 环境)           排序工具读主数据库、副数据库，按面板筛，交给排序规则排
//     3. 返回/      返回(排好的, 条件, …)      分页、换成卡片字段
// 用户id 由服务端核验身份后给（没登录给 null），不信小程序传的。
// 海报地址：网站对外提供主数据库海报文件夹的地址（部署时配）；没配、或者这边还没收到那张图，卡片就没有海报。
import { 整理输入 } from './用户输入/index.mjs';
import { 排序 } from './排序规则/排序工具.mjs';
import { 返回 } from './返回/index.mjs';
import { 海报 } from '../主数据库/index.mjs';

export function 呈现首页(请求, { 主库, 副库, 用户id = null, now = new Date(), 海报地址 = '', 海报目录 }) {
  const 条件 = 整理输入(请求);
  const 排好的 = 排序(条件, { 主库, 副库, 用户id, now });
  const 海报链接 = 文件 => (海报地址 && 海报.有(文件, { 目录: 海报目录 }) ? `${海报地址}/${文件}` : '');
  return 返回(排好的, 条件, { now, 海报链接 });
}
